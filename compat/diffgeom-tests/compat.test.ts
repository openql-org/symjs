import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { expect, it } from 'vitest';
import type { TestCase } from '../tests-harness';
import { runDiffgeomTestCase } from './harness';

it('measures the diffgeom unit-assertion corpus against the base subpath', () => {
  const read = (file: string) => JSON.parse(readFileSync(new URL(file, import.meta.url), 'utf8'));
  type Extraction = { omitted: { module: string; src: string; reason: string }[] };
  const unit: { cases: TestCase[]; extraction: Extraction } = read('./tests-corpus.json');
  const results = unit.cases.map((c) => ({
    c,
    result: runDiffgeomTestCase(c),
    key: `unit: ${c.module}: ${c.src} #${createHash('sha256').update(JSON.stringify(c)).digest('hex').slice(0, 16)}`,
  }));
  const failures = results.filter((r) => !['pass', 'equivalent'].includes(r.result.status));
  const omissions = unit.extraction.omitted.filter((o) => o.reason !== 'statement-or-setup');
  const extractionGaps = omissions.map((o, i) => [
    `extraction: unit: ${o.module}: ${o.src} #${i}`,
    `extractor: ${o.reason}`,
  ]);
  const path = new URL('./known-gaps.json', import.meta.url);
  const baseline: Record<string, string> = existsSync(path) ? read('./known-gaps.json') : {};
  if (process.env['UPDATE_KNOWN_GAPS'] === '1') {
    const gaps = Object.fromEntries([
      ...failures.map((r) => [
        r.key,
        'reason' in r.result
          ? r.result.reason
          : `Output differs: ${'got' in r.result ? r.result.got : r.result.status}`,
      ]),
      ...extractionGaps,
    ]);
    writeFileSync(path, JSON.stringify(gaps, null, 2) + '\n');
    writeFileSync(new URL('./extraction-gaps.json', import.meta.url), JSON.stringify(omissions, null, 2) + '\n');
  } else {
    expect(
      extractionGaps.filter(([key]) => !(key! in baseline)),
      'new extraction omissions',
    ).toEqual([]);
  }
  const totals = { cases: results.length, passed: results.length - failures.length, remaining: failures.length };
  writeFileSync(
    new URL('./report.json', import.meta.url),
    JSON.stringify(
      {
        reference: 'SymPy 1.14.0',
        totals,
        extraction: unit.extraction,
        results: results.map(({ c, ...r }) => ({ ...r, module: c.module, src: c.src, expected: c.expected })),
      },
      null,
      2,
    ) + '\n',
  );
  writeFileSync(
    new URL('./REPORT.md', import.meta.url),
    `# Differential geometry unit-test compatibility

Reference: SymPy 1.14.0. Generated by the diffgeom compatibility runner.

${totals.passed}/${totals.cases} extracted unit assertions pass. ${totals.remaining} replay failures remain. ${omissions.length} assertions are omitted by the extractor and tracked, with reasons, in [known-gaps.json](known-gaps.json) and [extraction-gaps.json](extraction-gaps.json). These are not counted as passes. Individual outcomes and extraction statistics are in [report.json](report.json).

The runner uses the shared assertion harness and the base \`@symjs/symjs/diffgeom\` subpath. Differential-geometry doctests belong to the [base corpus](../REPORT.md). Source tests additionally exercise round trips, chained tensor assertions and integral-curve equations that the extractor omits.

SymPy 1.14 mathematical errors are corrected: powers of vector fields raise RangeError; Lie derivatives of forms contract the correction tensor on the commutator arguments. Mixed-chart commutators retain vector order. Partial wedge contractions pad omitted slots before antisymmetrization.
`,
  );
  expect(results.length).toBeGreaterThan(0);
  expect(failures, JSON.stringify(failures, null, 2)).toEqual([]);
});
