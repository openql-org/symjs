"""Regenerate the singular points of SymPy 1.14's function classes (Function._singularities, read by
Function.is_singular) as packages/symjs/src/core/singularities.ts."""
import json
from pathlib import Path
import sympy
from sympy.core.function import Function

assert sympy.__version__ == '1.14.0'
classes = {}


def walk(cls):
    for sub in cls.__subclasses__():
        if sub.__module__.startswith('sympy.') and not sub.__module__.startswith('sympy.physics'):
            classes[sub.__name__] = sub
        walk(sub)


walk(Function)
table = {}
for name in sorted(classes):
    points = classes[name]._singularities
    if points is None:
        continue
    table[name] = points if isinstance(points, bool) else [str(p) for p in points]
header = ('// SPDX-License-Identifier: MIT\n'
          '// SPDX-FileCopyrightText: Copyright 2026 OpenQL Project\n'
          '// Generated by tools/sympy-reference/generators/gen_singularities.py from SymPy 1.14 (BSD-3-Clause).\n'
          '// Do not edit by hand.\n\n'
          '/**\n * The essential singularities and branch points of the function classes (SymPy\n'
          ' * Function._singularities): true or false for every argument, else the points (zoo for an\n'
          ' * infinite argument). Functions not listed are unknown.\n */\n'
          'export const SINGULARITIES: Readonly<Record<string, boolean | readonly string[]>> = ')
target = Path(__file__).resolve().parents[3] / 'packages/symjs/src/core/singularities.ts'
body = ''.join(f"  {json.dumps(name)}: {json.dumps(value)},\n" for name, value in table.items()).replace('"', "'")
target.write_text(header + '{\n' + body + '};\n')
print(len(table))
