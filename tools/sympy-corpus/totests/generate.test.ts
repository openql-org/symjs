/**
 * @file Converts the SymPy doctest and unit-test corpora into symjs tests written with the public API
 * (`packages/symjs/tests/<path>.corpus.test.ts`).
 *
 * Each case is replayed through the harness with the symjs entry points wrapped (trace.ts); the
 * public-API calls it made are printed as the test's code (program.ts) and the assertion compares
 * the result with SymPy's printed output. Every case becomes one test:
 * - `it` when symjs gives SymPy's result,
 * - `it.fails` when the case is written with the public API but symjs does not give SymPy's result yet,
 * - `it.todo` when the case cannot be written with the public API (yet), with its SymPy source.
 * `UPDATE_CORPUS_TESTS=1` (`bun run corpus:generate`) writes every file, then records the cases that do
 * not type-check (type-errors.json) and the cases whose generated test disagrees with the replay
 * (unreproduced.json); the next run writes those as `it.todo`. `CORPUS_RECHECK_TYPES=1` ignores both
 * records. Without UPDATE_CORPUS_TESTS the run only prints the tally: `ONLY=<module substring>`
 * selects cases and `SHOW=<n>` prints the first n tests of the first selected file.
 */

