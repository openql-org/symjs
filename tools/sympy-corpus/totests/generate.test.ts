interface CorpusCase {
  module: string;
  fn: string;
  src: string;
  expected: string;
  test?: string;
  line?: number;
  op?: string;
  raises?: string;
  post?: string;
  text?: boolean;
  pick?: number;
  pyFormat?: string;
  brackets?: string;
  ws?: boolean;
  unsupportedArg?: string;
  kwargs?: Record<string, unknown>;
}

type Kind = 'pass' | 'fails' | 'todo';

interface Generated {
  id: string;
  /** describe block: the SymPy source of the cases */
  group: string;
  name: string;
  kind: Kind;
  body: string[];
  /** for it.todo: why the case is not written with the public API */
  reason?: string;
  src: string;
  expected: string;
  imports: Map<string, Set<string>>;
  helpers: Set<string>;
}

const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const SRC = `${ROOT}packages/symjs/src/`;
const TESTS = `${ROOT}packages/symjs/tests/`;
const TYPE_ERRORS = `${ROOT}tools/sympy-corpus/totests/type-errors.json`;
const UNREPRODUCED = `${ROOT}tools/sympy-corpus/totests/unreproduced.json`;
const HEADER = 'Generated by tools/sympy-corpus/totests from the SymPy corpora; do not edit.';
const MODULE_PATHS: Readonly<Record<string, string>> = { index: '', diffgeom: '/diffgeom', parsing: '/parsing', categories: '/categories', plotting: '/plotting' };

const INVENTORY = new Map((JSON.parse(readFileSync(`${ROOT}tools/sympy-reference/scope-inventory.json`, 'utf8')) as { modules: { module: string; sources?: string[] }[] }).modules.map((m) => [m.module, m.sources ?? []]));

/** The symjs source file that ports a SymPy module (the first source of the scope inventory). */
/** The file exists with this exact name (the file system may ignore case). */
function exists(path: string): boolean {
  const slash = path.lastIndexOf('/');
  const dir = path.slice(0, slash + 1);
  return existsSync(path) && readdirSync(dir).includes(path.slice(slash + 1));
}

function sourcePath(module: string): string | undefined {
  const first = INVENTORY.get(module)?.[0];
  if (first !== undefined && exists(`${SRC}${first}`)) return first.replace(/\.ts$/, '');
  const parts = module.replace(/^sympy\./, '').split('.');
  const name = (parts.pop() ?? '').replace(/^_+/, '').replace(/_/g, '');
  const path = [...parts, name].join('/');
  return exists(`${SRC}${path}.ts`) ? path : undefined;
}

/** The test file of a case: doctests by their module, unit tests by the module they test (else their package). */
function testFile(c: CorpusCase): string | undefined {
  const m = /^(sympy(?:\.\w+)*)\.tests\.test_(\w+)$/.exec(c.module);
  if (!m) return sourcePath(c.module);
  return sourcePath(`${m[1]}.${m[2]}`) ?? sourcePath(m[1]!) ?? sourcePath(`${m[1]}.${m[1]!.split('.').pop()}`);
}

/** A test should run in under 2 seconds; the recorded replay is slower than the generated test. */
const SLOW_SECONDS = 4;

/** Python exceptions and the JS errors symjs throws for them. */
const RAISES: Readonly<Record<string, string>> = { ValueError: 'RangeError', ZeroDivisionError: 'RangeError', IndexError: 'RangeError', KeyError: 'RangeError' };

const caseId = (c: CorpusCase): string => `${c.module}:${c.test ?? ''}:${c.line ?? ''} #${createHash('sha256').update(JSON.stringify(c)).digest('hex').slice(0, 20)}`;

it('converts the corpora', async () => {
  const H = await import('../harness');
  const T = await import('../tests-harness');
  const tr = await import('./trace');
  const P = await import('./program');
  const helpers = await import('../../../packages/symjs/tests/sympy-str');
  const { equivalent } = await import('../../../packages/symjs/tests/sympy-equivalent');
  /** The printed input the equivalence check compares against (a form function returning its input is not a result). */
  const inputOf = (c: CorpusCase): string | undefined => tr.quiet(() => {
    const t = (c as { self?: unknown; args?: unknown[] }).self ?? (c as { args?: unknown[] }).args?.[0];
    if (t === undefined) return undefined;
    try {
      return H.fmt(H.deserialize(t as never));
    } catch {
      return undefined;
    }
  });
  const sj = await import('../../../packages/symjs/src');

  const gaps = JSON.parse(readFileSync(`${ROOT}tools/sympy-corpus/tests-known-gaps.json`, 'utf8')) as { timeouts: string[] };
  const timeouts = new Set(gaps.timeouts);
  const typeErrors = new Set<string>(existsSync(TYPE_ERRORS) && !process.env['CORPUS_RECHECK_TYPES'] ? JSON.parse(readFileSync(TYPE_ERRORS, 'utf8')) as string[] : []);
  const unreproduced = new Set<string>(existsSync(UNREPRODUCED) && !process.env['CORPUS_RECHECK_TYPES'] ? JSON.parse(readFileSync(UNREPRODUCED, 'utf8')) as string[] : []);

  const isJsList = (v: unknown): boolean => v instanceof H.JsList || (v instanceof H.JsTuple && v.isList);
  /** The public value of a harness result and the bracket kinds of its arrays (preorder). */
  const toPublic = (hv: unknown, kinds: string[]): unknown => {
    if (hv instanceof H.JsList || hv instanceof H.JsTuple) {
      kinds.push(isJsList(hv) ? 'l' : 't');
      return hv.items.map((x) => toPublic(x, kinds));
    }
    if (Array.isArray(hv)) {
      kinds.push('t');
      return hv.map((x) => toPublic(x, kinds));
    }
    if (hv instanceof H.JsDict) return new Map(hv.entries.map(([k, x]) => [toPublic(k, kinds), toPublic(x, kinds)]));
    if (hv instanceof H.JsSet) return new Set(hv.items.map((x) => toPublic(x, kinds)));
    return hv;
  };
  /** The kinds the harness gives arrays printed by Python's str() (withBrackets: listed kinds, then tuples). */
  const bracketsOf = (hv: unknown, given: string): string => {
    const out: string[] = [];
    let next = 0;
    const walk = (v: unknown): void => {
      if (Array.isArray(v) || v instanceof H.JsList) {
        out.push(given[next++] === 'l' ? 'l' : 't');
        (Array.isArray(v) ? v : v.items).forEach(walk);
      } else if (v instanceof H.JsTuple) {
        next++;
        out.push(v.isList ? 'l' : 't');
        v.items.forEach(walk);
      } else if (v instanceof Map || v instanceof H.JsDict) {
        for (const [a, b] of v instanceof Map ? v : v.entries) { walk(a); walk(b); }
      } else if (v instanceof Set || v instanceof H.JsSet) {
        (v instanceof Set ? [...v] : v.items).forEach(walk);
      }
    };
    walk(hv);
    return out.join('').replace(/l+$/, '');
  };
  const absent = (v: unknown): boolean => v === null || v === undefined || v === 'unknown' || tr.quiet(() => sj.isNoMatch(v) || sj.isUnsolved(v));
  /** The last library call that returned each value, and the value of each call, for the current recording. */
  let lastCall = new Map<unknown, ResultOf>();
  let lastAbsent: ResultOf | undefined;
  let valueOf = new Map<unknown, unknown>();
  const indexResults = (): void => {
    lastCall = new Map();
    lastAbsent = undefined;
    valueOf = new Map();
    for (const r of tr.results) {
      const v = tr.unwrap(r.value);
      const result = new P.ResultOf(r.node);
      lastCall.set(v, result);
      if (absent(r.value)) lastAbsent = result;
      valueOf.set(r.node, v);
    }
  };
  /** The result as library values: objects and primitives are traced back to the call that returned them last. */
  const fromLibrary = (pv: unknown): unknown => {
    if (pv instanceof Map || pv instanceof Set || Array.isArray(pv)) {
      if (Array.isArray(pv)) return pv.map(fromLibrary);
      if (pv instanceof Map) return new Map([...pv].map(([k, v]) => [fromLibrary(k), fromLibrary(v)]));
      return new Set([...pv].map(fromLibrary));
    }
    const objectLike = (typeof pv === 'object' && pv !== null) || typeof pv === 'function';
    const found = lastCall.get(objectLike ? tr.unwrap(pv) : pv) ?? (!objectLike && absent(pv) ? lastAbsent : undefined);
    if (found !== undefined) return found;
    if (objectLike && tr.provenance(pv) !== undefined) return pv;
    throw new P.Unprintable(objectLike ? 'a result object that did not come from the library' : 'a primitive result that no library call returned');
  };
  const deepUnwrap = (v: unknown): unknown => {
    if (Array.isArray(v)) return v.map(deepUnwrap);
    if (v instanceof Map) return new Map([...v].map(([k, x]) => [deepUnwrap(k), deepUnwrap(x)]));
    if (v instanceof Set) return new Set([...v].map(deepUnwrap));
    if (v instanceof P.ResultOf) return valueOf.get(v.node);
    return tr.unwrap(v);
  };

  const out = new Map<string, Generated[]>();
  const tally = new Map<string, number>();
  const count = (k: string): void => { tally.set(k, (tally.get(k) ?? 0) + 1); };

  const progress = process.env['CORPUS_PROGRESS'];
  const convert = (c: CorpusCase, group: string, name: string, unit: boolean): void => {
    const file = testFile(c);
    if (file === undefined) return count('no source file');
    const id = caseId(c);
    if (progress !== undefined) writeFileSync(progress, `${group} ${name} ${id}\n`);
    const list = out.get(file) ?? [];
    out.set(file, list);
    const base = { id, group, name, src: c.src, expected: c.expected, imports: new Map<string, Set<string>>(), helpers: new Set<string>(), body: [] as string[] };
    const todo = (reason: string): void => {
      count(`todo: ${reason.replace(/\d+/g, 'N').slice(0, 70)}`);
      list.push({ ...base, kind: 'todo', reason });
    };
    if (c.pyFormat !== undefined) return todo('printed with a Python number format');
    if (c.kwargs && '_random_prec' in c.kwargs) return todo('an upstream private random fixture');
    if (unit && c.fn === '.random') return todo("a draw from Python's seeded random generator");
    if (unit && timeouts.has(T.testCaseKey(c as never))) return todo('the replay exceeds its deadline');
    if (typeErrors.has(id)) return todo('the arguments do not type-check against the public API');
    if (unreproduced.has(id)) return todo('the generated test does not reproduce the replay');
    tr.resetResults();
    let observation: Record<string, unknown> | undefined;
    const alias: Readonly<Record<string, string>> = { '.is_nonnegative': '.isNonNegative', '.is_nonzero': '.isNonZero', '.is_nonpositive': '.isNonPositive' };
    const fn = alias[c.fn];
    const replay = fn === undefined ? c : { ...c, fn };
    const started = performance.now();
    const { value: outcome0 } = tr.record(() => H.runCase(replay as never, (ev) => { observation = ev as Record<string, unknown>; }));
    const seconds = (performance.now() - started) / 1000;
    if (seconds > SLOW_SECONDS) return todo(`the case takes more than ${SLOW_SECONDS} seconds`);
    const outcome = unit ? T.assertionOutcome(c as never, outcome0, observation as never) : outcome0;
    if (outcome.status === 'unsupported') return todo((outcome as { reason?: string }).reason ?? 'unsupported');
    const equivalentForm = outcome.status === 'equivalent';
    let passing = equivalentForm || outcome.status === 'pass' && !('exceptionMismatch' in outcome && outcome.exceptionMismatch !== undefined);
    if (c.raises !== undefined && !passing && tr.thrown !== undefined) {
      // Python's raises (isinstance) and toThrow (instanceof) accept a subclass of the expected error
      const expectedClass = RAISES[c.raises] ?? c.raises;
      const E: unknown = ['RangeError', 'TypeError'].includes(expectedClass) ? globalThis[expectedClass as 'RangeError'] : tr.quiet(() => tr.unwrap(Reflect.get(sj, expectedClass)));
      if (typeof E === 'function' && tr.thrown.error instanceof E && observation !== undefined && 'error' in observation && observation['error'] === tr.thrown.error) passing = true;
    }
    let realValue: unknown;
    if (c.post !== undefined) {
      // the result before Python's str()/len()/list(): replayed without the projection
      realValue = observation && 'value' in observation ? observation['value'] : undefined;
      tr.resetResults();
      observation = undefined;
      const raw = { ...replay, post: undefined, brackets: undefined };
      tr.record(() => H.runCase(raw as never, (ev) => { observation = ev as Record<string, unknown>; }));
    }
    const p = new P.Program();
    let body: string[];
    try {
      const thrown = tr.thrown;
      const libraryError = thrown !== undefined && observation !== undefined && 'error' in observation && observation['error'] === thrown.error;
      if (c.raises !== undefined) {
        // the call that is expected to raise: the one that threw, or for a case that did not raise, the last call
        const node = libraryError ? thrown.node : tr.results.at(-1)?.node;
        if (node === undefined) throw new P.Unprintable('no library call');
        const cls = RAISES[c.raises] ?? c.raises;
        const global = ['RangeError', 'TypeError', 'Error', 'SyntaxError', 'ReferenceError'].includes(cls);
        if (!global && Reflect.get(sj, cls) === undefined) throw new P.Unprintable(`the error class ${cls} is not public`);
        const r = new P.ResultOf(node);
        p.count(r);
        const e = p.expr(r);
        body = p.finish([...p.lines, `expect(() => ${e}).toThrow(${global ? cls : p.importName('index', cls)});`]);
      } else if (libraryError) {
        if (passing) throw new P.Unprintable('an error for a passing case');
        const r = new P.ResultOf(thrown.node);
        p.count(r);
        const e = p.expr(r);
        body = p.finish([...p.lines, `expect(sympyStr(${e})).toBe(${P.quote(c.expected)});`]);
      } else {
        if (observation === undefined || !('value' in observation)) throw new P.Unprintable(outcome.status === 'error' ? 'an error outside the library' : 'no value');
        const kinds: string[] = [];
        indexResults();
        const pv = fromLibrary(toPublic(observation['value'], kinds));
        const value = deepUnwrap(pv);
        const op = c.op ?? '==';
        const positive = !(op === '!=' || op === 'is not');
        // the assertion: a helper applied to the result, its printed form and the expected text
        let check: { call: (e: string) => string; actual: () => unknown; expected: unknown };
        if (c.post !== undefined) {
          const shown: string[] = [];
          toPublic(realValue, shown);
          const k = bracketsOf(observation['value'], c.brackets ?? '');
          const q = (x: string): string => (x ? `, ${P.quote(x)}` : '');
          switch (c.post) {
            case 'str': check = { call: (e) => `pyStr(${e}${q(k)})`, actual: () => helpers.pyStr(value, k), expected: c.expected }; break;
            case 'repr': check = { call: (e) => `pyRepr(${e}${q(k)})`, actual: () => helpers.pyRepr(value, k), expected: c.expected }; break;
            case 'len': check = { call: (e) => `pyLen(${e})`, actual: () => helpers.pyLen(value), expected: Number(c.expected) }; break;
            case 'str-items': check = { call: (e) => `sympyStr(strItems(${e}))`, actual: () => helpers.sympyStr(helpers.strItems(value)), expected: c.expected }; break;
            case 'list': case 'tuple': {
              const ks = shown.join('').replace(/l+$/, '');
              check = { call: (e) => `sympyStr(pyItems(${e})${q(ks)})`, actual: () => helpers.sympyStr(helpers.pyItems(value), ks), expected: c.expected };
              break;
            }
            default: throw new P.Unprintable(`printed with ${c.post}`);
          }
          p.helpers.add(c.post === 'str' ? 'pyStr' : c.post === 'repr' ? 'pyRepr' : c.post === 'len' ? 'pyLen' : c.post === 'str-items' ? 'strItems' : 'pyItems');
        } else if (c.text) {
          const ws = Boolean(c.ws);
          if (typeof value !== 'string') throw new P.Unprintable('text that is not a string');
          check = { call: (e) => `text(${e}${ws ? ', true' : ''})`, actual: () => helpers.text(value, ws), expected: helpers.text(c.expected, ws) };
          p.helpers.add('text');
        } else if (equivalentForm) {
          // the same value in another form (equal at sample points, or simplify(a - b) == 0)
          const k = kinds.join('').replace(/l+$/, '');
          const input = inputOf(c);
          const opts = `{ fn: ${P.quote(c.fn)}${input === undefined ? '' : `, input: ${P.quote(input)}`} }`;
          check = {
            call: (e) => `equivalent(sympyStr(${e}${k ? `, ${P.quote(k)}` : ''}), ${P.quote(c.expected)}, [${p.declaredSymbols().map((x) => x.token).join(', ')}], ${opts})`,
            actual: () => equivalent(helpers.sympyStr(value, kinds.join('')), c.expected, p.declaredSymbols().map((x) => new sj.Sym(x.name, x.assume)), { fn: c.fn, ...(input === undefined ? {} : { input }) }),
            expected: true,
          };
          p.helpers.add('equivalent');
        } else {
          const k = kinds.join('').replace(/l+$/, '');
          const exact = tr.quiet(() => helpers.sympyStr(value, kinds.join(''))) === c.expected;
          if (exact || !passing || !positive) check = { call: (e) => `sympyStr(${e}${k ? `, ${P.quote(k)}` : ''})`, actual: () => helpers.sympyStr(value, kinds.join('')), expected: c.expected };
          else {
            // the same result up to the order of set items, list or tuple brackets and layout
            check = { call: (e) => `sympyMatches(${e}, ${P.quote(c.expected)}${k ? `, ${P.quote(k)}` : ''})`, actual: () => helpers.sympyMatches(value, c.expected, kinds.join('')), expected: true };
            p.helpers.add('sympyMatches');
          }
        }
        p.count(pv);
        for (const r of tr.results) if (r.value === undefined && r.node.k === 'method' && p.uses_(r.node.obj)) p.effect(r.node);
        const e = p.expr(pv);
        const actual = tr.quiet(check.actual);
        // Python's != and `is not` compare structure: a different printed form satisfies them
        if (!positive && !c.text && c.post === undefined && !equivalentForm) passing = actual !== check.expected;
        if (passing && (positive ? actual !== check.expected : actual === check.expected)) throw new P.Unprintable(equivalentForm ? 'an equivalent form that the declared symbols do not confirm' : `the printed result differs (${String(actual).slice(0, 40)})`);
        const lit = typeof check.expected === 'number' || typeof check.expected === 'boolean' ? String(check.expected) : P.quote(String(check.expected));
        const assertion = `expect(${check.call(e)})${positive ? '' : '.not'}.toBe(${lit});`;
        if (c.text) {
          const u = p.importName('index', 'pprintUseUnicode');
          body = p.finish([`const unicode = ${u}(false);`, 'try {', ...p.lines.map((l) => `  ${l}`), `  ${assertion}`, '} finally {', `  ${u}(unicode);`, '}']);
        } else body = p.finish([...p.lines, assertion]);
      }
    } catch (e) {
      if (e instanceof P.Unprintable) return todo(e.message);
      return todo(`the conversion failed: ${e instanceof Error ? e.message.split('\n')[0] : String(e)}`);
    }
    count(passing ? 'it' : 'it.fails');
    list.push({ ...base, kind: passing ? 'pass' : 'fails', body, imports: p.imports, helpers: p.helpers });
  };

  const only = process.env['ONLY'];
  // a test file holds the cases of several corpus modules; writing a subset would drop the others
  if (only && process.env['UPDATE_CORPUS_TESTS']) throw new Error('ONLY selects cases to inspect; UPDATE_CORPUS_TESTS writes every file');
  const doc = (JSON.parse(readFileSync(`${ROOT}tools/sympy-corpus/corpus.json`, 'utf8')) as { cases: CorpusCase[] }).cases;
  for (const c of doc) {
    if (only && !c.module.includes(only)) continue;
    convert(c, `doctests of ${c.module}`, (c.src.split('\n')[0] ?? '').slice(0, 100), false);
  }
  const index = JSON.parse(readFileSync(`${ROOT}tools/sympy-corpus/tests-corpus/index.json`, 'utf8')) as { categories: Record<string, { shards: { file: string }[] }> };
  for (const category of Object.values(index.categories)) {
    for (const shard of category.shards) {
      for (const c of JSON.parse(readFileSync(`${ROOT}tools/sympy-corpus/tests-corpus/${shard.file}`, 'utf8')) as CorpusCase[]) {
        if (only && !c.module.includes(only)) continue;
        convert(c, `${c.module.replace(/\./g, '/')}.py`, `${c.test ?? ''}:${c.line ?? ''}`, true);
      }
    }
  }
  console.log([...tally].sort((a, b) => b[1] - a[1]).map(([k, n]) => `${n}\t${k}`).join('\n'));

  if (process.env['UPDATE_CORPUS_TESTS']) {
    const ranges = new Map<string, [number, number, string][]>();
    for (const f of generatedFiles(TESTS)) rmSync(f);
    for (const [file, cases] of out) {
      const { text, lines } = render(file, cases);
      const path = `${TESTS}${file}.corpus.test.ts`;
      writeFileSync(path, text);
      ranges.set(path, lines);
    }
    // cases whose arguments the public types reject are written as it.todo by the next run
    const tsc = spawnSync(`${ROOT}node_modules/.bin/tsc`, ['--noEmit', '-p', ROOT], { encoding: 'utf8', maxBuffer: 1 << 28, cwd: ROOT });
    const bad = new Set<string>();
    const outside: string[] = [];
    for (const m of tsc.stdout.matchAll(/^(.+?\.corpus\.test\.ts)\((\d+),\d+\): error/gm)) {
      const path = m[1]!.startsWith('/') ? m[1]! : `${ROOT}${m[1]}`;
      const line = Number(m[2]);
      const hit = ranges.get(path)?.find(([a, b]) => line >= a && line <= b);
      if (hit) bad.add(hit[2]);
      else outside.push(m[0]);
    }
    for (const m of tsc.stdout.matchAll(/^(?!.+?\.corpus\.test\.ts\().+?\(\d+,\d+\): error.*$/gm)) outside.push(m[0]);
    if (outside.length > 0) console.log(`type errors outside the cases:\n${outside.join('\n')}`);
    writeFileSync(TYPE_ERRORS, JSON.stringify([...new Set([...typeErrors, ...bad])].sort(), null, 1) + '\n');
    console.log(`type errors: ${bad.size}`);
    // cases whose generated test disagrees with the replay (an it that fails, an it.fails that passes)
    const report = `${ROOT}node_modules/.corpus-tests.json`;
    spawnSync(`${ROOT}node_modules/.bin/vitest`, ['run', '--reporter=json', `--outputFile=${report}`, '--includeTaskLocation', '.corpus.test.ts'], { encoding: 'utf8', maxBuffer: 1 << 28, cwd: ROOT });
    const results = JSON.parse(readFileSync(report, 'utf8')) as { testResults: { name: string; message?: string; assertionResults: { status: string; location?: { line: number } }[] }[] };
    rmSync(report);
    const stale = new Set<string>();
    const failedFiles: string[] = [];
    for (const file of results.testResults) {
      if (file.message) failedFiles.push(`${file.name}: ${file.message.split('\n')[0] ?? ''}`);
      for (const a of file.assertionResults) {
        if (a.status !== 'failed') continue;
        const line = a.location?.line ?? 0;
        const hit = ranges.get(file.name)?.find(([x, y]) => line >= x && line <= y);
        if (hit) stale.add(hit[2]);
        else failedFiles.push(`${file.name}:${line}`);
      }
    }
    if (failedFiles.length > 0) console.log(`failures outside the cases:\n${failedFiles.join('\n')}`);
    writeFileSync(UNREPRODUCED, JSON.stringify([...new Set([...unreproduced, ...stale])].sort(), null, 1) + '\n');
    console.log(`unreproduced: ${stale.size}`);
  } else if (process.env['SHOW']) {
    const [file, cases] = [...out][0] ?? [];
    if (file !== undefined && cases !== undefined) console.log(render(file, cases.slice(0, Number(process.env['SHOW']))).text);
  }
  expect(tally.size).toBeGreaterThan(0);
});

function generatedFiles(dir: string): string[] {
  const found: string[] = [];
  for (const name of readdirSync(dir)) {
    const path = `${dir}${name}`;
    if (statSync(path).isDirectory()) found.push(...generatedFiles(`${path}/`));
    else if (name.endsWith('.corpus.test.ts') && readFileSync(path, 'utf8').includes(HEADER)) found.push(path);
  }
  return found;
}

function render(file: string, cases: Generated[]): { text: string; lines: [number, number, string][] } {
  const up = '../'.repeat(file.split('/').length);
  const here = up.slice(3) || './';
  const imports = new Map<string, Set<string>>();
  const helpers = new Set<string>();
  for (const c of cases) {
    if (c.kind === 'todo') continue;
    if (c.body.some((l) => l.includes('sympyStr('))) helpers.add('sympyStr');
    for (const [m, names] of c.imports) for (const n of names) {
      const set = imports.get(m) ?? new Set<string>();
      imports.set(m, set);
      set.add(n);
    }
    for (const h of c.helpers) helpers.add(h);
  }
  const hasTests = cases.some((c) => c.kind !== 'todo');
  const lines = [
    '// SPDX-License-Identifier: MIT',
    '// SPDX-FileCopyrightText: Copyright 2026 OpenQL Project',
    '',
    `/** SymPy's doctests and unit tests of this module with SymPy's printed results. ${HEADER} */`,
    '',
    `import { describe, ${hasTests ? 'expect, ' : ''}it } from 'vitest';`,
    ...[...imports].sort().map(([m, names]) => `import { ${[...names].sort().join(', ')} } from '${up}src${MODULE_PATHS[m] ?? `/${m}`}';`),
    ...(helpers.size > (helpers.has('equivalent') ? 1 : 0) ? [`import { ${[...helpers].filter((h) => h !== 'equivalent').sort().join(', ')} } from '${here}sympy-str';`] : []),
    ...(helpers.has('equivalent') ? [`import { equivalent } from '${here}sympy-equivalent';`] : []),
  ];
  const groups = new Map<string, Generated[]>();
  for (const c of cases) {
    const g = groups.get(c.group) ?? [];
    groups.set(c.group, g);
    g.push(c);
  }
  const ranges: [number, number, string][] = [];
  for (const [group, list] of groups) {
    lines.push('', `describe(${JSON.stringify(group)}, () => {`);
    const seen = new Map<string, number>();
    for (const c of list) {
      const n = (seen.get(c.name) ?? 0) + 1;
      seen.set(c.name, n);
      const title = JSON.stringify(n === 1 ? c.name : `${c.name} (${n})`);
      const start = lines.length + 1;
      if (c.kind === 'todo') {
        lines.push(`  // ${(c.reason ?? '').replace(/[\n\r\u2028\u2029]/g, ' ')}`, ...`${c.src}\n=> ${c.expected}`.split(/\r\n|[\n\r\u2028\u2029]/).map((l) => `  //   ${l}`), `  it.todo(${title});`);
      } else {
        lines.push(`  it${c.kind === 'fails' ? '.fails' : ''}(${title}, () => {`, ...c.body.map((l) => `    ${l}`), '  });');
      }
      ranges.push([start, lines.length, c.id]);
    }
    lines.push('});');
  }
  return { text: lines.join('\n') + '\n', lines: ranges };
}
