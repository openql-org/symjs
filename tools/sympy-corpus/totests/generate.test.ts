import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { expect, it, vi } from 'vitest';
import type { ResultOf } from './program';

vi.mock('../../../packages/symjs/src', async (orig) => (await import('./trace')).traceModule(await orig(), 'index'));
vi.mock('../../../packages/symjs/src/diffgeom', async (orig) => (await import('./trace')).traceModule(await orig(), 'diffgeom'));
vi.mock('../../../packages/symjs/src/parsing', async (orig) => (await import('./trace')).traceModule(await orig(), 'parsing'));
