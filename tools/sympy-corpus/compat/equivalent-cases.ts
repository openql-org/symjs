import { writeFileSync } from 'node:fs';

/** A replayed case that agreed with SymPy only by equivalence: the printed results differ. */
export interface EquivalentCase { id: string; fn: string; got: string; expected: string }

/** A table cell: pipes escaped, long values shortened. */
const cell = (s: string): string => (s.length > 200 ? `${s.slice(0, 200)}…` : s).replace(/\|/g, '\\|').replace(/`/g, "'").replace(/\n/g, ' ');

/** Writes docs/<corpus>-equivalent-cases.md: the cases counted as equivalent, not exact. */
export function writeEquivalentCases(corpus: 'doctest' | 'unittest', cases: readonly EquivalentCase[]): void {
  const lines = [
    `# SymPy ${corpus === 'doctest' ? 'doctest' : 'unit-test'} cases that agree by equivalence only (\`bun run corpus:compat\`)`,
    '',
    'Generated by the harness replay; do not edit.',
    'symjs gives a mathematically equal result printed differently from SymPy (`packages/symjs/tests/sympy-equivalent.ts`).',
    '',
    `**${cases.length}** cases.`,
    '',
    '| Case | Function | symjs | SymPy |',
    '| --- | --- | --- | --- |',
    ...[...cases].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0)).map((c) => `| ${cell(c.id)} | ${cell(c.fn)} | \`${cell(c.got)}\` | \`${cell(c.expected)}\` |`),
  ];
  writeFileSync(new URL(`../../../docs/${corpus}-equivalent-cases.md`, import.meta.url), lines.join('\n') + '\n');
}
