/**
 * @file SymPy sympy.combinatorics.named_groups: SymmetricGroup,
 * AlternatingGroup, CyclicGroup, DihedralGroup, AbelianGroup and RubikGroup,
 * with the properties SymPy records for them.
 */

import { afNew, Permutation } from './permutations';
import { PermutationGroupNode } from './permgroups';
import { DirectProduct } from './groupconstructs';
import { rubik } from './generators';

const positive = (n: number): void => {
  if (!Number.isSafeInteger(n) || n < 1) throw new RangeError('group size must be a positive integer');
};
const range = (n: number): number[] => Array.from({ length: n }, (_, i) => i);

/** SymPy AbelianGroup(*cyclic_orders): the direct product of cyclic groups of the given orders. */
export function AbelianGroup(...cyclicOrders: number[]): PermutationGroupNode {
  let degree = 0;
  let order = 1n;
  const groups = cyclicOrders.map((size) => {
    degree += size;
    order *= BigInt(size);
    return CyclicGroup(size);
  });
  const G = DirectProduct(...groups);
  G.known.isAbelian = true;
  G.degreeValue = degree;
  G.known.order = order;
  return G;
}

/** SymPy AlternatingGroup(n): the even permutations of n points, generated by (0 1 2) and an n-cycle or (1 ... n-1). */
export function AlternatingGroup(n: number): PermutationGroupNode {
  positive(n);
  if (n < 3) return new PermutationGroupNode([new Permutation([0])]);
  const gen1 = range(n);
  [gen1[0], gen1[1], gen1[2]] = [1, 2, 0];
  const gen2 = n % 2 ? [...range(n - 1).map((i) => i + 1), 0] : [0, ...range(n - 2).map((i) => i + 2), 1];
  const gens = gen1.every((x, i) => x === gen2[i]) ? [gen1] : [gen1, gen2];
  const G = new PermutationGroupNode(gens.map(afNew), { dups: false });
  setAlternatingGroupProperties(G, n, n);
  G.known.isAlt = true;
  return G;
}

/** SymPy set_alternating_group_properties(G, n, degree). */
function setAlternatingGroupProperties(G: PermutationGroupNode, n: number, degree: number): void {
  G.known.isAbelian = n < 4;
  G.known.isNilpotent = n < 4;
  G.known.isSolvable = n < 5;
  G.degreeValue = degree;
  G.known.isTransitive = true;
  G.known.isDihedral = false;
}

/** SymPy CyclicGroup(n): the group generated by the n-cycle (0 1 ... n-1). */
export function CyclicGroup(n: number): PermutationGroupNode {
  positive(n);
  const G = new PermutationGroupNode([afNew([...range(n - 1).map((i) => i + 1), 0])]);
  G.known.isAbelian = true;
  G.known.isNilpotent = true;
  G.known.isSolvable = true;
  G.degreeValue = n;
  G.known.isTransitive = true;
  G.known.order = BigInt(n);
  G.known.isDihedral = n === 2;
  return G;
}

/** SymPy DihedralGroup(n): the symmetries of a regular n-gon (n = 1, 2 act on 2 and 4 points). */
export function DihedralGroup(n: number): PermutationGroupNode {
  positive(n);
  if (n === 1) return new PermutationGroupNode([new Permutation([1, 0])]);
  if (n === 2) return new PermutationGroupNode([new Permutation([1, 0, 3, 2]), new Permutation([2, 3, 0, 1]), new Permutation([3, 2, 1, 0])]);
  const G = new PermutationGroupNode([afNew([...range(n - 1).map((i) => i + 1), 0]), afNew(range(n).reverse())]);
  G.known.isNilpotent = (n & (n - 1)) === 0;
  G.known.isDihedral = true;
  G.known.isAbelian = false;
  G.known.isSolvable = true;
  G.degreeValue = n;
  G.known.isTransitive = true;
  G.known.order = BigInt(2 * n);
  return G;
}

/** SymPy SymmetricGroup(n): all permutations of n points, generated by an n-cycle and a transposition. */
export function SymmetricGroup(n: number): PermutationGroupNode {
  positive(n);
  let G: PermutationGroupNode;
  if (n === 1) G = new PermutationGroupNode([new Permutation([0])]);
  else if (n === 2) G = new PermutationGroupNode([new Permutation([1, 0])]);
  else {
    const gen2 = range(n);
    [gen2[0], gen2[1]] = [1, 0];
    G = new PermutationGroupNode([afNew([...range(n - 1).map((i) => i + 1), 0]), afNew(gen2)]);
  }
  G.known.isAbelian = n < 3;
  G.known.isNilpotent = n < 3;
  G.known.isSolvable = n < 5;
  G.degreeValue = n;
  G.known.isTransitive = true;
  G.known.isDihedral = n === 2 || n === 3;
  G.known.isSym = true;
  return G;
}

/** SymPy RubikGroup(n): the group of the n x n x n Rubik's cube (its faces' moves). */
export function RubikGroup(n: number): PermutationGroupNode {
  if (!Number.isSafeInteger(n) || n <= 1) throw new RangeError('Invalid cube. n has to be greater than 1');
  return new PermutationGroupNode(rubik(n));
}
