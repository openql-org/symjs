/**
 * @file SymPy sympy.combinatorics.named_groups: SymmetricGroup,
 * AlternatingGroup, CyclicGroup, DihedralGroup, AbelianGroup and RubikGroup,
 * with the properties SymPy records for them.
 */

import { afNew, Permutation } from './permutations';
import { PermutationGroupNode } from './permgroups';
import { DirectProduct } from './groupconstructs';
import { rubik } from './generators';

const positive = (n: number): void => {
  if (!Number.isSafeInteger(n) || n < 1) throw new RangeError('group size must be a positive integer');
};
const range = (n: number): number[] => Array.from({ length: n }, (_, i) => i);

/**
 * The direct product of cyclic groups of the given orders.
 * @param cyclicOrders - The orders of the cyclic direct factors.
 * @returns The resulting permutation group.
 * @see SymPy `sympy.combinatorics.named_groups.AbelianGroup`
 * @example
 * ```ts
 * import { AbelianGroup } from '@symjs/symjs';
 * AbelianGroup(3, 4); // => PermutationGroup([
 * //       (6)(0 1 2),
 * //       (3 4 5 6)])
 * ```
 */
export function AbelianGroup(...cyclicOrders: number[]): PermutationGroupNode {
  let degree = 0;
  let order = 1n;
  const groups = cyclicOrders.map((size) => {
    degree += size;
    order *= BigInt(size);
    return CyclicGroup(size);
  });
  const G = DirectProduct(...groups);
  G.known.isAbelian = true;
  G.degreeValue = degree;
  G.known.order = order;
  return G;
}

/**
 * The even permutations of n points, generated by (0 1 2) and an n-cycle or (1 ... n-1).
 * @param n - The number of points in the natural group action.
 * @returns The group of even permutations on the specified number of points.
 * @see SymPy `sympy.combinatorics.named_groups.AlternatingGroup`
 * @example
 * ```ts
 * import { AlternatingGroup } from '@symjs/symjs';
 * AlternatingGroup(4).order(); // => 12
 * ```
 */
export function AlternatingGroup(n: number): PermutationGroupNode {
  positive(n);
  if (n < 3) return new PermutationGroupNode([new Permutation([0])]);
  const gen1 = range(n);
  [gen1[0], gen1[1], gen1[2]] = [1, 2, 0];
  const gen2 = n % 2 ? [...range(n - 1).map((i) => i + 1), 0] : [0, ...range(n - 2).map((i) => i + 2), 1];
  const gens = gen1.every((x, i) => x === gen2[i]) ? [gen1] : [gen1, gen2];
  const G = new PermutationGroupNode(gens.map(afNew), { dups: false });
  setAlternatingGroupProperties(G, n, n);
  G.known.isAlt = true;
  return G;
}

/**
 * Set the known properties of an alternating group A_n acting on degree points.
 * @param G - The ambient group.
 * @param n - The number of points in the natural group action.
 * @param degree - The number of points acted on.
 * @see SymPy `sympy.combinatorics.named_groups.set_alternating_group_properties`
 */
export function setAlternatingGroupProperties(G: PermutationGroupNode, n: number, degree: number): void {
  G.known.isAbelian = n < 4;
  G.known.isNilpotent = n < 4;
  G.known.isSolvable = n < 5;
  G.degreeValue = degree;
  G.known.isTransitive = true;
  G.known.isDihedral = false;
}

/**
 * The group generated by the n-cycle (0 1 ... n-1).
 * @param n - The number of points in the natural group action.
 * @returns The permutation group generated by a cycle of the given length.
 * @see SymPy `sympy.combinatorics.named_groups.CyclicGroup`
 * @example
 * ```ts
 * import { CyclicGroup } from '@symjs/symjs';
 * CyclicGroup(6).order(); // => 6
 * ```
 */
export function CyclicGroup(n: number): PermutationGroupNode {
  positive(n);
  const G = new PermutationGroupNode([afNew([...range(n - 1).map((i) => i + 1), 0])]);
  G.known.isAbelian = true;
  G.known.isNilpotent = true;
  G.known.isSolvable = true;
  G.degreeValue = n;
  G.known.isTransitive = true;
  G.known.order = BigInt(n);
  G.known.isDihedral = n === 2;
  return G;
}

/**
 * The symmetries of a regular n-gon (n = 1, 2 act on 2 and 4 points).
 * @param n - The number of sides of the polygon.
 * @returns The resulting permutation group.
 * @see SymPy `sympy.combinatorics.named_groups.DihedralGroup`
 * @example
 * ```ts
 * import { DihedralGroup } from '@symjs/symjs';
 * DihedralGroup(5).order(); // => 10
 * ```
 */
export function DihedralGroup(n: number): PermutationGroupNode {
  positive(n);
  if (n === 1) return new PermutationGroupNode([new Permutation([1, 0])]);
  if (n === 2) return new PermutationGroupNode([new Permutation([1, 0, 3, 2]), new Permutation([2, 3, 0, 1]), new Permutation([3, 2, 1, 0])]);
  const G = new PermutationGroupNode([afNew([...range(n - 1).map((i) => i + 1), 0]), afNew(range(n).reverse())]);
  G.known.isNilpotent = (n & (n - 1)) === 0;
  G.known.isDihedral = true;
  G.known.isAbelian = false;
  G.known.isSolvable = true;
  G.degreeValue = n;
  G.known.isTransitive = true;
  G.known.order = BigInt(2 * n);
  return G;
}

/**
 * Set the known properties of a symmetric group S_n acting on degree points.
 * @param G - The ambient group.
 * @param n - The number of points in the natural group action.
 * @param degree - The number of points acted on.
 * @see SymPy `sympy.combinatorics.named_groups.set_symmetric_group_properties`
 */
export function setSymmetricGroupProperties(G: PermutationGroupNode, n: number, degree: number): void {
  G.known.isAbelian = n < 3;
  G.known.isNilpotent = n < 3;
  G.known.isSolvable = n < 5;
  G.degreeValue = degree;
  G.known.isTransitive = true;
  G.known.isDihedral = n === 2 || n === 3;
}

/**
 * All permutations of n points, generated by an n-cycle and a transposition.
 * @param n - The number of points in the natural group action.
 * @returns The resulting permutation group.
 * @see SymPy `sympy.combinatorics.named_groups.SymmetricGroup`
 * @example
 * ```ts
 * import { SymmetricGroup } from '@symjs/symjs';
 * SymmetricGroup(4).order(); // => 24
 * ```
 */
export function SymmetricGroup(n: number): PermutationGroupNode {
  positive(n);
  let G: PermutationGroupNode;
  if (n === 1) G = new PermutationGroupNode([new Permutation([0])]);
  else if (n === 2) G = new PermutationGroupNode([new Permutation([1, 0])]);
  else {
    const gen2 = range(n);
    [gen2[0], gen2[1]] = [1, 0];
    G = new PermutationGroupNode([afNew([...range(n - 1).map((i) => i + 1), 0]), afNew(gen2)]);
  }
  setSymmetricGroupProperties(G, n, n);
  G.known.isSym = true;
  return G;
}

/**
 * The group of the n x n x n Rubik's cube (its faces' moves).
 * @param n - The number of cubies along one edge.
 * @returns The resulting permutation group.
 * @throws RangeError when the cube side length is less than two.
 * @see SymPy `sympy.combinatorics.named_groups.RubikGroup`
 * @example
 * ```ts
 * import { RubikGroup } from '@symjs/symjs';
 * RubikGroup(2).isGroup; // => True
 * ```
 */
export function RubikGroup(n: number): PermutationGroupNode {
  if (!Number.isSafeInteger(n) || n <= 1) throw new RangeError('Invalid cube. n has to be greater than 1');
  return new PermutationGroupNode(rubik(n));
}
