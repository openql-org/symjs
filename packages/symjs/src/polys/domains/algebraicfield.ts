type QP = PythonMPQ[];

/**
 * The number-field algorithms of the maximal order and the prime ideals,
 * registered by polys/numberfields/basis.ts and primes.ts (which build on
 * the domain matrices, themselves built on the domains).
 * @internal
 */
export const numberFieldHooks: {
  galoisGroup?: (K: AlgebraicField, options: GaloisGroupOptions) => GaloisGroupResult;
  roundTwo?: (K: AlgebraicField, radicals: Map<bigint, Submodule>) => [Submodule, Rational];
  primeDecomp?: (p: bigint, ZK: Submodule, dK: Rational, radical: Submodule | undefined) => PrimeIdeal[];
} = {};

/**
 * An algebraic number field QQ<a,...>.
 *
 * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField`
 * @example
 * ```ts
 * import { QQ, ex, factor } from '@symjs/symjs';
 *
 * const K = QQ.algebraicField(ex`sqrt(2)`);
 * factor(ex`x**2 - 2`, { domain: K }); // => (x - sqrt(2))*(x + sqrt(2))
 * ```
 */
export class AlgebraicField extends Domain {
  /** The identifier for the underlying coefficient domain. */
  readonly ground = 'EX' as const;
  /**
   * Indicates whether the domain supports field arithmetic.
   *
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.is_Field`
   */
  readonly isField = true;
  /**
   * The primitive element theta as an algebraic number.
   *
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.ext`
   */
  readonly ext: AlgebraicNumber;
  /**
   * The extensions the field was made from.
   *
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.orig_ext`
   */
  readonly origExt: readonly Expr[];
  /**
   * Computes the remainder on division by the supplied divisor.
   *
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.mod`
   */
  readonly mod: QP;
  private readonly baseDomain: Domain;
  private readonly atomRepresentations = new Map<string,ANP>();
  private reducedPowers: { powers: FieldPoly[]; generators: Expr[] } | undefined;
  private maximalOrderCache: [Submodule, Rational] | undefined;
  private readonly nilradicalsModP = new Map<bigint, Submodule>();
  protected override get unificationKind(): UnificationKind {
    return 'ALG';
  }
  protected override get algebraicExtensions(): readonly Expr[] {
    return this.origExt;
  }
  /**
   * Checks the characteristic of the coefficient ring.
   *
   * @returns Whether the characteristic is zero.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.has_CharacteristicZero`
   */
  override get hasCharacteristicZero(): boolean {
    return true;
  }
  /**
   * The field generated by the extensions over QQ. A single AlgebraicNumber given with its minimal
   * polynomial (e.g. a symbol standing for a root of it) or with an alias is the primitive element
   * itself, and its alias names the field's generator.
   *
   * @param dom - Base coefficient domain.
   * @param ext - Algebraic elements to adjoin to the base field.
   * @throws DomainError when the ground domain is not a rational field.
   */
  constructor(dom: Domain, ...ext: (ExprLike | AlgebraicNumber)[]) {
    super();
    if (!dom.equals(QQ)) throw new DomainError('ground domain must be a rational field');
    this.baseDomain = dom;
    this.origExt = ext.map((e) => (e instanceof AlgebraicNumber ? (e.alias ?? e.asExpr()) : sympify(e)));
    const single = ext.length === 1 ? first(ext) : undefined;
    if (single instanceof AlgebraicNumber && isPrimitive(single)) this.ext = single;
    else {
      // a single generator is its own primitive element (toNumberField would search for one)
      const e = single === undefined ? toNumberField(ext) : new AlgebraicNumber(single instanceof AlgebraicNumber ? single.asExpr() : single);
      const alias = single instanceof AlgebraicNumber ? single.alias : undefined;
      this.ext = alias === undefined ? e : new AlgebraicNumber(e.root, [1, 0], { minpoly: e.minpoly(), alias });
    }
    this.mod = this.ext
      .minpoly()
      .allCoeffs()
      .map((c) => QQ.convert(c));
  }
  /** The expression of the primitive element: its alias, or its value. */
  private get generator(): Expr {
    return this.ext.alias ?? this.ext.asExpr();
  }
  /**
   * The underlying coefficient domain.
   *
   * @returns The underlying coefficient domain.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.dom`
   */
  override get dom(): Domain {
    return this.baseDomain;
  }
  /**
   * The ground domain QQ.
   *
   * @returns The coefficient domain.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.domain`
   */
  get domain(): Domain {
    return this.baseDomain;
  }
  /**
   * Formats the value as text.
   *
   * @returns The printable representation.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.__str__`
   */
  toString(): string {
    return `${this.baseDomain.toString()}<${str(this.generator)}>`;
  }
  /**
   * Compares the two operands for equality.
   *
   * @param o - Value to compare against.
   * @returns Whether the operands are equal.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.__eq__`
   */
  override equals(o: Domain): boolean {
    return o instanceof AlgebraicField && o.toString() === this.toString();
  }
  /**
   * The element with these coefficients in theta.
   *
   * @param args - Value or coefficients defining the domain element.
   * @returns The newly constructed element.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.new`
   */
  override new(...args: unknown[]): ANP {
    return new ANP(first(args), this.mod, this.baseDomain);
  }
  /**
   * Coerces a rational or an algebraic expression into the field.
   *
   * @param a - Element on which to operate.
   * @param base - Source domain when converting an existing element.
   * @returns The value represented in the target domain.
   * @throws CoercionFailed when the value cannot be represented in the target domain.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.convert`
   */
  override convert(a: unknown, base?: Domain): ANP {
    const v = base !== undefined && !base.equals(this) ? base.toSympy(a) : a;
    if (v instanceof ANP) return v;
    if (groundRational(v) !== undefined) return this.new([v]);
    if (!(v instanceof Expr)) throw new CoercionFailed(`cannot convert ${String(a)} to ${this.toString()}`);
    const theta = this.generator;
    try { return this.fromGeneratorPolynomial(v, theta); }
    catch (error) { if (!(error instanceof CoercionFailed)) throw error; }
    try {
      return this.new(toNumberField(v, this.ext).coeffs());
    } catch {
      throw new CoercionFailed(`${str(v)} is not a valid algebraic number in ${this.toString()}`);
    }
  }
  /** Evaluate rational expressions in the primitive element in the quotient field. */
  private fromGeneratorPolynomial(v: Expr, theta: Expr): ANP {
    const visit = (e: Expr): ANP => {
      if (e.key === theta.key) return this.new([1,0]);
      if (e instanceof Rational) return this.new([e]);
      if (e instanceof Add) return e.args.reduce((a,b) => a.add(visit(b)),this.new([]));
      if (e instanceof Mul) return e.args.reduce((a,b) => a.mul(visit(b)),this.new([1]));
      if (e instanceof Pow && e.exp instanceof Rational && e.exp.isInteger) {
        let b=visit(e.base),k=e.exp.p,r=this.new([1]);
        if(k<0n){b=r.div(b);k=-k;}
        for(;k;k>>=1n){if(k&1n)r=r.mul(b);b=b.mul(b);}
        return r;
      }
      const cached=this.atomRepresentations.get(e.key);
      if(cached!==undefined)return cached;
      try {
        const value=this.new(toNumberField(e,this.ext).coeffs());
        this.atomRepresentations.set(e.key,value);
        return value;
      } catch {throw new CoercionFailed(`${str(e)} is not a rational expression in ${str(theta)}`);}
    };
    return visit(v);
  }
  /**
   * Checks whether the input already belongs to the native element type.
   *
   * @param a - Element on which to operate.
   * @returns Whether the value is a native element of the domain.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.of_type`
   */
  override ofType(a: unknown): boolean {
    return a instanceof ANP;
  }
  /** Reduce powers of an additive primitive element modulo the minimal polynomial of each summand. */
  private makeReducedPowers(theta: Add): { powers: FieldPoly[]; generators: Expr[] } {
    const terms = theta.args.map(splitCoeff).filter(([, term]) => !term.equals(S.One));
    const generators = terms.map(([, term]) => term);
    const dummy = new Dummy('a');
    const monomial = (index: number, exponent: number) => terms.map((_, i) => i === index ? exponent : 0);
    const image = new FieldPoly(QQ, terms.length, [
      ...theta.args.filter((term) => term instanceof Rational).map((term) => [monomial(-1, 0), term] as const),
      ...terms.map(([coefficient], i) => [monomial(i, 1), coefficient] as const),
    ]);
    const moduli = generators.map((g, i) => new FieldPoly(QQ, terms.length,
      minimalPolynomial(g, dummy, { polys: true }).terms().map(([m, c]) => [monomial(i, first(m)), c])));
    const powers = [image.one];
    for (let n = 1; n < this.mod.length - 1; n++) {
      powers.push(moduli.reduce((p, m) => p.div(m)[1], at(powers, n - 1).mul(image)));
    }
    return { powers, generators };
  }
  /**
   * Expresses the value using symbolic expression nodes.
   *
   * @param a - Element on which to operate.
   * @returns The corresponding symbolic expression.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.to_sympy`
   */
  override toSympy(a: unknown): Expr {
    if (!(a instanceof ANP)) return super.toSympy(a);
    const theta = this.generator;
    const n = a.rep.length - 1;
    if (theta instanceof Add && n > 0) {
      const { powers, generators } = this.reducedPowers ??= this.makeReducedPowers(theta);
      const sum = a.rep.reduce((p, c, i) => p.add(at(powers, n - i).scale(c)), first(powers).zero);
      return expand(sum.asExpr(generators));
    }
    return expand(add(...a.rep.map((c, i) => mul(Rational.of(c.numerator, c.denominator), pow(theta, n - i)))));
  }
  /**
   * Reduces the expression to the canonical form for this domain.
   *
   * @param e - Expression to represent in this domain.
   * @returns The canonical expression in this domain.
   */
  canon(e: Expr): Expr {
    return this.toSympy(this.convert(e));
  }
  /**
   * Interprets a symbolic expression in this domain.
   *
   * @param e - Expression to represent in this domain.
   * @returns The expression converted into the domain.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.from_sympy`
   */
  fromSympy(e: ExprLike): Expr {
    return this.canon(sympify(e));
  }
  /**
   * Finds the field associated with this domain.
   *
   * @returns The associated field.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.get_field`
   */
  getField(): Domain {
    return this;
  }
  /**
   * Finds the ring associated with this domain.
   *
   * @returns The associated ring.
   * @throws DomainError when the field has no associated ring.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.get_ring`
   */
  override getRing(): Domain {
    throw new DomainError(`there is no ring associated with ${this.toString()}`);
  }
  /**
   * Tests for the additive identity.
   *
   * @param a - Element on which to operate.
   * @returns Whether the value equals zero.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.is_zero`
   */
  override isZero(a: unknown): boolean {
    return a instanceof ANP ? a.isZero : super.isZero(a);
  }
  /**
   * Tests the sign of an element according to the ordering convention of this domain.
   *
   * @param a - Element on which to operate.
   * @returns Whether the value is positive in this domain.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.is_positive`
   */
  override isPositive(a: unknown): boolean {
    return this.convert(a).LC().sign > 0;
  }
  /**
   * Tests the sign of an element according to the ordering convention of this domain.
   *
   * @param a - Element on which to operate.
   * @returns Whether the value is negative in this domain.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.is_negative`
   */
  override isNegative(a: unknown): boolean {
    return a instanceof ANP ? a.LC().sign < 0 : super.isNegative(a);
  }
  /**
   * Divides by the supplied divisor.
   *
   * @param a - Dividend in the coefficient domain.
   * @param b - Divisor.
   * @returns The quotient.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.div`
   */
  override div(a: unknown, b: unknown): [ANP, ANP] {
    return [this.exquo(a, b), this.new(0n)];
  }
  /**
   * Divides in the coefficient domain, requiring exact divisibility.
   *
   * @param a - Dividend in the coefficient domain.
   * @param b - Divisor.
   * @returns The exact quotient.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.exquo`
   */
  override exquo(a: unknown, b: unknown): ANP {
    return this.convert(a).div(this.convert(b));
  }
  /**
   * Computes the remainder on division by the supplied divisor.
   *
   * @param _a - Dividend in the coefficient domain.
   * @param _b - Divisor.
   * @returns The remainder after division.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.rem`
   */
  override rem(_a: unknown, _b: unknown): ANP {
    return this.new(0n);
  }
  /**
   * Computes a greatest common divisor in this domain.
   *
   * @param a - Element on which to operate.
   * @param b - Second operand.
   * @returns A greatest common divisor.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.gcd`
   */
  override gcd(a: unknown, b: unknown): ANP {
    return this.new(this.convert(a).isZero && this.convert(b).isZero ? 0n : 1n);
  }
  /**
   * Computes a least common multiple in this domain.
   *
   * @param a - Element on which to operate.
   * @param b - Second operand.
   * @returns A least common multiple.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.lcm`
   */
  override lcm(a: unknown, b: unknown): ANP {
    return this.convert(a).mul(this.convert(b));
  }
  /**
   * The field with more extensions.
   *
   * @param exts - Algebraic generators to adjoin.
   * @returns The field with the additional generators adjoined.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.algebraic_field`
   */
  override algebraicField(...exts: ExprLike[]): Domain {
    return new AlgebraicField(this.baseDomain, ...this.origExt, ...exts);
  }
  /**
   * The element as an algebraic number.
   *
   * @param a - Element on which to operate.
   * @returns The corresponding algebraic number.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.to_alg_num`
   */
  toAlgNum(a: ANP): AlgebraicNumber {
    return this.ext.fieldElement(a.rep.map((c) => Rational.of(c.numerator, c.denominator)));
  }
  private roundTwo(): [Submodule, Rational] {
    this.maximalOrderCache ??= defined(numberFieldHooks.roundTwo, 'number field module (import roundTwo from the polys entry)')(this, this.nilradicalsModP);
    return this.maximalOrderCache;
  }
  /**
   * The maximal order (ring of integers) as a submodule of the power basis of the primitive element.
   *
   * @returns The ring of integers of the number field.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.maximal_order`
   */
  maximalOrder(): Submodule {
    return this.roundTwo()[0];
  }
  /**
   * An integral basis: the basis of the maximal order as elements of the field (ANP), as expressions
   * with fmt 'sympy', or as algebraic numbers with fmt 'alg'.
   *
   * @param fmt - Representation in which to return the result.
   * @returns A basis of the ring of integers in the requested representation.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.integral_basis`
   */
  integralBasis(fmt?: undefined): ANP[];
  /**
   * An integral basis: the basis of the maximal order as elements of the field (ANP), as expressions
   * with fmt 'sympy', or as algebraic numbers with fmt 'alg'.
   *
   * @param fmt - Representation in which to return the result.
   * @returns A basis of the ring of integers in the requested representation.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.integral_basis`
   */
  integralBasis(fmt: 'sympy'): Expr[];
  /**
   * An integral basis: the basis of the maximal order as elements of the field (ANP), as expressions
   * with fmt 'sympy', or as algebraic numbers with fmt 'alg'.
   *
   * @param fmt - Representation in which to return the result.
   * @returns A basis of the ring of integers in the requested representation.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.integral_basis`
   */
  integralBasis(fmt: 'alg'): AlgebraicNumber[];
  /**
   * An integral basis: the basis of the maximal order as elements of the field (ANP), as expressions
   * with fmt 'sympy', or as algebraic numbers with fmt 'alg'.
   *
   * @param fmt - Representation in which to return the result.
   * @returns A basis of the ring of integers in the requested representation.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.integral_basis`
   */
  integralBasis(fmt?: 'sympy' | 'alg'): ANP[] | Expr[] | AlgebraicNumber[];
  integralBasis(fmt?: 'sympy' | 'alg'): ANP[] | Expr[] | AlgebraicNumber[] {
    const ZK = this.maximalOrder();
    const pb = ZK.powerBasisAncestor();
    const M = ZK.QQMatrix;
    const [m, n] = M.shape;
    const B = Array.from({ length: n }, (_, j) => this.new(pb.toFieldCoeffs(M.extractSlice([0, m], [j, j + 1]).flat().map(asRational)).reverse()));
    if (fmt === 'sympy') return B.map((b) => this.toSympy(b));
    if (fmt === 'alg') return B.map((b) => this.toAlgNum(b));
    return B;
  }
  /**
   * The discriminant of the field.
   *
   * @returns The discriminant.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.discriminant`
   */
  discriminant(): Rational {
    return this.roundTwo()[1];
  }
  /**
   * The prime ideals of the maximal order lying above the rational prime p.
   *
   * @param p - Rational prime.
   * @returns The prime ideals over the rational prime.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.primes_above`
   */
  primesAbove(p: IntLike): PrimeIdeal[] {
    const [ZK, dK] = this.roundTwo();
    const q = asInt(p, 'p');
    return defined(numberFieldHooks.primeDecomp, 'number field module (import primeDecomp from the polys entry)')(q, ZK, dK, this.nilradicalsModP.get(q));
  }
  /**
   * The Galois group of the defining minimal polynomial.
   *
   * @param options - Group representation and trial limits.
   * @returns The group and its alternating-group membership flag.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.galois_group`
   */
  galoisGroup(options: GaloisGroupOptions = {}): GaloisGroupResult {
    return defined(numberFieldHooks.galoisGroup, 'import galoisGroup from the polys entry')(this, options);
  }
  /**
   * Gives the characteristic of this extension of the rational field.
   *
   * @returns The characteristic of the coefficient domain.
   * @see SymPy `sympy.polys.domains.algebraicfield.AlgebraicField.characteristic`
   */
  characteristic(): bigint {
    return 0n;
  }
}

/** The algebraic number has the coefficients [1, 0]: it is its primitive element. */
function isPrimitive(a: AlgebraicNumber): boolean {
  const cs = a.coeffs();
  return cs.length === 2 && first(cs).equals(1) && at(cs, 1).equals(0);
}

/** A QQ element (a Rational) of a domain matrix. */
const asRational = (e: Expr): Rational => expectType(e, (x): x is Rational => x instanceof Rational, 'rational');

domainHooks.algebraicField = (K, exts) => new AlgebraicField(K.getField(), ...exts);
