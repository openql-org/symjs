import { NotImplementedError } from '../../core/errors';
import { first } from '../../core/guard';
import { asInt, type IntLike } from '../../ntheory/intutil';
import type { Expr, ExprLike } from '../../core/nodes';
import { mul } from '../../core/ops';
import { str } from '../../printing/str';
import { type Domain, domainHooks } from '../domains';
import type { SubModule } from './modules';

/**
 * An ideal represented by a submodule of a rank-one free module.
 *
 * @see SymPy `sympy.polys.agca.ideals.ModuleImplementedIdeal`
 */
export class ModuleImplementedIdeal {
  /**
   * The rank-one submodule representing the ideal.
   *
   * @see SymPy `sympy.polys.agca.ideals.ModuleImplementedIdeal.__module__`
   */
  readonly module: SubModule;
  /**
   * Builds the ideal spanned by the given ring elements.
   *
   * @param ring - Coefficient ring.
   * @param gens - Generators in their given order.
   */
  constructor(
    /**
     * The underlying ring.
     *
     * @see SymPy `sympy.polys.agca.ideals.ModuleImplementedIdeal.ring`
     */
    readonly ring: Domain, gens: readonly ExprLike[]) {
    this.module = ring.freeModule(1).submodule(...gens.map((g) => [g]));
  }
  /**
   * Lists the ring elements generating this ideal.
   *
   * @returns The generating elements.
   * @see SymPy `sympy.polys.agca.ideals.ModuleImplementedIdeal.gens`
   */
  get gens(): readonly Expr[] { return this.module.gens.map((g) => first(g.data)); }
  /**
   * Formats the value as text.
   *
   * @returns The printable representation.
   * @see SymPy `sympy.polys.agca.ideals.ModuleImplementedIdeal.__repr__`
   */
  toString(): string { return `<${this.gens.map(str).join(',')}>`; }
  /**
   * Tests membership of the specified element.
   *
   * @param element - Element to represent or transform.
   * @returns Whether the element is a member.
   * @see SymPy `sympy.polys.agca.ideals.ModuleImplementedIdeal.contains`
   */
  contains(element: ExprLike): boolean { return this.module.contains([element]); }
  /**
   * Checks that all the supplied elements belong to this object.
   *
   * @param elements - Entries in their given order.
   * @returns Whether every supplied element is a member.
   * @see SymPy `sympy.polys.agca.ideals.ModuleImplementedIdeal.subset`
   */
  subset(elements: Iterable<ExprLike> | ModuleImplementedIdeal): boolean {
    return [...(elements instanceof ModuleImplementedIdeal ? elements.gens : elements)].every((g) => this.contains(g));
  }
  /**
   * Compares the two operands for equality.
   *
   * @param other - Value to compare against.
   * @returns Whether the operands are equal.
   * @see SymPy `sympy.polys.agca.ideals.ModuleImplementedIdeal._equals`
   */
  equals(other: ModuleImplementedIdeal): boolean { return this.ring.equals(other.ring) && this.module.equals(other.module); }
  /**
   * Checks whether the ideal contains the ring identity.
   *
   * @returns Whether the ideal contains one.
   * @see SymPy `sympy.polys.agca.ideals.ModuleImplementedIdeal.is_whole_ring`
   */
  isWholeRing(): boolean { return this.module.isFullModule(); }
  /**
   * Tests for the additive identity.
   *
   * @returns Whether the value equals zero.
   * @see SymPy `sympy.polys.agca.ideals.ModuleImplementedIdeal.is_zero`
   */
  isZero(): boolean { return this.module.isZero(); }
  /**
   * Express a member of the ideal as a combination of its generators.
   *
   * @param element - Element to represent or transform.
   * @returns Coefficients expressing the element in the given generators.
   * @see SymPy `sympy.polys.agca.ideals.ModuleImplementedIdeal.in_terms_of_generators`
   */
  inTermsOfGenerators(element: ExprLike): Expr[] { return this.module.inTermsOfGenerators([element]); }
  /**
   * Reduces the element modulo the generators.
   *
   * @param element - Element to represent or transform.
   * @param fully - Request full reduction of the representative.
   * @returns A reduced representative of the element.
   * @see SymPy `sympy.polys.agca.ideals.ModuleImplementedIdeal.reduce_element`
   */
  reduceElement(element: ExprLike, fully = false): Expr { return first(this.module.reduceElement([element], fully).data); }
  private checkRing(other: ModuleImplementedIdeal): void {
    if (!this.ring.equals(other.ring)) throw new RangeError('ideals must have the same ring');
  }
  /**
   * Generates the sum from the generators of both operands.
   *
   * @param other - Ideal in the same ring.
   * @returns The sum generated by the two operands.
   * @see SymPy `sympy.polys.agca.ideals.ModuleImplementedIdeal.union`
   */
  union(other: ModuleImplementedIdeal): ModuleImplementedIdeal {
    this.checkRing(other);
    return this.ring.ideal(...this.gens, ...other.gens);
  }
  /**
   * Finds the ideal common to the two operands.
   *
   * @param other - Ideal in the same ring.
   * @returns The intersection, with generator relations when requested.
   * @see SymPy `sympy.polys.agca.ideals.ModuleImplementedIdeal.intersect`
   */
  intersect(other: ModuleImplementedIdeal): ModuleImplementedIdeal {
    this.checkRing(other);
    return this.ring.ideal(...this.module.intersect(other.module).gens.map((g) => first(g.data)));
  }
  /**
   * Generates an ideal from all products of a generator of each ideal.
   *
   * @param other - Ideal in the same ring.
   * @returns The product in operand order.
   * @see SymPy `sympy.polys.agca.ideals.ModuleImplementedIdeal.product`
   */
  product(other: ModuleImplementedIdeal): ModuleImplementedIdeal {
    this.checkRing(other);
    return this.ring.ideal(...this.gens.flatMap((a) => other.gens.map((b) => mul(a, b))));
  }
  /**
   * Adds the other operand to this value.
   *
   * @param other - Addend.
   * @returns The sum of the operands.
   * @see SymPy `sympy.polys.agca.ideals.ModuleImplementedIdeal.__add__`
   */
  add(other: ModuleImplementedIdeal): ModuleImplementedIdeal {
    return this.union(other);
  }
  /**
   * The product with an ideal, or with the ideal generated by an element.
   *
   * @param other - Factor on the right.
   * @returns The product in operand order.
   * @see SymPy `sympy.polys.agca.ideals.ModuleImplementedIdeal.__mul__`
   */
  mul(other: ModuleImplementedIdeal | ExprLike): ModuleImplementedIdeal {
    return this.product(other instanceof ModuleImplementedIdeal ? other : this.ring.ideal(other));
  }
  /**
   * Raises the value to the specified power.
   *
   * @param n - Exponent to which to raise the value.
   * @returns The value raised to the given exponent.
   * @throws NotImplementedError when the exponent is negative.
   * @see SymPy `sympy.polys.agca.ideals.ModuleImplementedIdeal.__pow__`
   */
  pow(n: IntLike): ModuleImplementedIdeal {
    const k = asInt(n, 'exponent');
    if (k < 0n) throw new NotImplementedError('negative powers of ideals are not defined');
    let result = this.ring.ideal(1);
    for (let i = 0n; i < k; i++) result = result.mul(this);
    return result;
  }
  /**
   * Computes the ideal of elements whose product with the divisor ideal lies in this ideal.
   *
   * @param other - Divisor ideal.
   * @returns The ideal quotient.
   * @see SymPy `sympy.polys.agca.ideals.ModuleImplementedIdeal.quotient`
   */
  quotient(other: ModuleImplementedIdeal): ModuleImplementedIdeal {
    this.checkRing(other);
    return this.module.moduleQuotient(other.module);
  }
}

domainHooks.ideal = (ring, gens) => new ModuleImplementedIdeal(ring, gens);
