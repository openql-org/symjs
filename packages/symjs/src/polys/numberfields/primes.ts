const int = (e: Expr): bigint => rat(e).p;

/** The maximal order must be a submodule of a power basis starting with 1, with a square HNF matrix of maximal rank. */
function checkFormalConditionsForMaximalOrder(submodule: Submodule): void {
  const prefix = 'The submodule representing the maximal order should ';
  let cond: string | undefined;
  if (!submodule.isPowerBasisSubmodule()) cond = 'be a direct submodule of a power basis.';
  else if (!submodule.startsWithUnity()) cond = 'have 1 as its first generator.';
  else if (!submodule.isSqMaxrankHNF()) cond = 'have square matrix, of maximal rank, in Hermite Normal Form.';
  if (cond !== undefined) throw new StructureError(prefix + cond);
}

/** The power basis of a submodule of a power basis. */
const powerBasisOf = (ZK: Submodule): PowerBasis => ZK.powerBasisAncestor();

/**
 * A prime ideal of the maximal order ZK, generated by the rational prime p
 * and an element alpha, with ramification index e and inertia degree f
 * (SymPy PrimeIdeal). Its str is `(p, alpha)` (or `(p)` for an inert prime)
 * and its repr `[ (p, alpha) e=1, f=3 ]`.
 */
export class PrimeIdeal {
  readonly ZK: Submodule;
  readonly p: bigint;
  readonly alpha: PowerBasisElement;
  readonly f: number;
  readonly e: number;
  private testFactorElement: PowerBasisElement | undefined;
  constructor(ZK: Submodule, p: IntLike, alpha: PowerBasisElement, f: number, e?: number) {
    checkFormalConditionsForMaximalOrder(ZK);
    this.ZK = ZK;
    this.p = asInt(p, 'p');
    this.alpha = alpha;
    this.f = f;
    this.e = e ?? this.valuation(ZK.mul(this.p));
  }
  /** SymPy str: (p, alpha), or (p) for an inert prime. */
  toString(): string {
    if (this.isInert) return `(${this.p})`;
    return `(${this.p}, ${str(this.alpha.asExpr())})`;
  }
  /** The prime p stays prime in ZK (f = n). */
  get isInert(): boolean {
    return this.f === this.ZK.n;
  }
  /**
   * SymPy repr: `[ (p, alpha) e=.., f=.. ]` with alpha written in fieldGen
   * (default: the variable of the field's polynomial), or only `(p, alpha)`
   * with justGens.
   */
  repr(fieldGen?: Expr, justGens = false): string {
    const gen = fieldGen ?? first(powerBasisOf(this.ZK).T.gens);
    let alphaRep = str(this.alpha.numerator(gen).asExpr());
    if (this.alpha.denom > 1n) alphaRep = `(${alphaRep})/${this.alpha.denom}`;
    const gens = `(${this.p}, ${alphaRep})`;
    if (justGens) return gens;
    return `[ ${gens} e=${this.e}, f=${this.f} ]`;
  }
  /** The ideal as a submodule of the power basis: pZK + alpha*ZK. */
  asSubmodule(): Submodule {
    const M = this.ZK.mul(this.p).add(this.ZK.mul(this.alpha));
    M.presetProperties(false, true);
    return M;
  }
  equals(other: unknown): boolean {
    return other instanceof PrimeIdeal && this.asSubmodule().equals(other.asSubmodule());
  }
  /** The sum with a submodule or another ideal, as a submodule. */
  add(other: Submodule | PrimeIdeal): Submodule {
    return this.asSubmodule().add(other instanceof PrimeIdeal ? other.asSubmodule() : other);
  }
  /** The product with a rational number, an element, a submodule or another ideal, as a submodule. */
  mul(other: Parameters<Submodule['mul']>[0] | PrimeIdeal): Submodule {
    return this.asSubmodule().mul(other instanceof PrimeIdeal ? other.asSubmodule() : other);
  }
  /** The e-th power: ZK for e = 0, the ideal for e = 1, else a submodule. */
  pow(e: number): Submodule | PrimeIdeal {
    if (e === 0) return this.ZK;
    if (e === 1) return this;
    return this.asSubmodule().pow(e);
  }
  /** An element beta of ZK with beta*P in pZK and beta not in pZK (Cohen, Sec. 4.8.3). */
  testFactor(): PowerBasisElement {
    this.testFactorElement ??= computeTestFactor(this.p, [this.alpha], this.ZK);
    return this.testFactorElement;
  }
  /** The valuation of an ideal (a submodule of the power basis) at this prime. */
  valuation(I: Submodule): number {
    return primeValuation(I, this);
  }
  /** The representative of an element of the power basis modulo this ideal. */
  reduceElement(elt: ModuleElement): ModuleElement {
    return this.asSubmodule().reduceElement(elt);
  }
  /** The representative of a field element modulo this ideal. */
  reduceANP(a: ANP): ANP {
    const elt = powerBasisOf(this.ZK).elementFromANP(a);
    return asPBE(this.reduceElement(elt)).toANP();
  }
  /** The representative of an algebraic number of the field modulo this ideal. */
  reduceAlgNum(a: AlgebraicNumber): AlgebraicNumber {
    const pb = powerBasisOf(this.ZK);
    const red = this.reduceElement(pb.elementFromAlgNum(a));
    return a.fieldElement(pb.toFieldCoeffs(red.QQCol.flat().map(rat)).reverse());
  }
}

function asPBE(e: ModuleElement): PowerBasisElement {
  return e.overPowerBasis();
}

/** A test factor for the ideal generated by p and gens: an element of the kernel of multiplication by the gens modulo p. */
function computeTestFactor(p: bigint, gens: readonly PowerBasisElement[], ZK: Submodule): PowerBasisElement {
  checkFormalConditionsForMaximalOrder(ZK);
  const E = ZK.endomorphismRing();
  const matrices = gens.map((g) => E.innerEndomorphism(g).matrix(p));
  const B = DomainMatrix.zeros([0, ZK.n], GF(p)).vstack(...matrices);
  const N = B.nullspace();
  const x = N.extractSlice([0, 1], [0, N.shape[1]]).transpose();
  return powerBasisOf(ZK).call(dmMul(ZK.matrix, x.convertTo(ZZ)), ZK.denom);
}

/**
 * The valuation v_P(I) of an ideal I of the maximal order (a submodule of
 * the power basis) at the prime ideal P (SymPy prime_valuation; Cohen,
 * Alg. 4.8.17).
 *
 * SymPy loops forever for the zero ideal; its valuation is infinite, so
 * Infinity is returned. A nonzero ideal has full rank, so a singular
 * nonzero matrix is not an ideal (RangeError).
 */
export function primeValuation(I: Submodule, P: PrimeIdeal): number {
  const p = P.p, ZK = P.ZK;
  const n = ZK.n, W = ZK.matrix, d = ZK.denom;
  let A = dmMul(W.convertTo(QQ).inv(), I.matrix).scalarmul(Rational.of(d)).div(Rational.of(I.denom)).convertTo(ZZ);
  const D = int(A.det());
  if (D === 0n) {
    if (A.isZeroMatrix) return Infinity;
    throw new RangeError('primeValuation: I must be a nonzero ideal');
  }
  if (pmod(D, p) !== 0n) return 0;
  const beta = P.testFactor();
  let v = 0;
  for (;;) {
    A = dmMul(W, A);
    for (let j = 0; j < n; j++) {
      const c = powerBasisOf(ZK).call(A.extractSlice([0, n], [j, j + 1]), d).mul(beta);
      const cs = ZK.represent(c).flat();
      for (let i = 0; i < n; i++) A.setitem(i, j, at(cs, i));
    }
    if (pmod(int(A.getitemSympy(n - 1, n - 1)), p) !== 0n) break;
    // Cohen's step: stop unless every entry is divisible by p. SymPy skips this test unless p divides the
    // index d**n/det(W) of ZZ[theta] in ZK, and then raises CoercionFailed, e.g. for 25*ZK at the prime
    // (5, x + 1) of x**3 + x**2 - 2*x + 8, whose valuation is 2.
    const Aq = A.div(Rational.of(p));
    if (Aq.flat().some((c) => rat(c).q !== 1n)) break;
    A = Aq.convertTo(ZZ);
    v += 1;
  }
  return v;
}

/**
 * A second generator alpha of the ideal generated by p and gens (elements
 * of the power basis), with N(alpha)/N(ideal) prime to p: the ideal is
 * (p, alpha) (Cohen, Alg. 6.2.9, step 9). The ideal's norm is p**f.
 */
function twoEltRep(gens: readonly PowerBasisElement[], ZK: Submodule, p: bigint, f: number): PowerBasisElement {
  checkFormalConditionsForMaximalOrder(ZK);
  const pb = powerBasisOf(ZK);
  const T = pb.T;
  if (gens.every((g) => g.mod(p).equiv(0))) return pb.zero();
  const Np = p ** BigInt(f);
  const omega = ZK.basisElementPullbacks();
  // omega[0] == 1 is omitted
  const beta: ModuleElement[] = [...omega.slice(1).map((om) => om.mul(p)), ...gens];
  const search = coeffSearch(beta.length, 1);
  // the search is infinite and finds a suitable alpha (every ideal has a two-element form, Cohen, Alg. 6.2.9)
  for (;;) {
    const c = search.next().value;
    let alpha: ModuleElement = pb.zero();
    c.forEach((ci, i) => (alpha = alpha.add(at(beta, i).mul(ci))));
    const a = alpha.overPowerBasis();
    const N = fdiv(a.norm(T).p, Np);
    if (pmod(N, p) !== 0n) return a.mod(p).overPowerBasis();
  }
}

/** The primes above p when p does not divide the index of ZZ[theta] in ZK (Dedekind; Cohen, Thm. 4.8.13). */
function primeDecompEasyCase(p: bigint, ZK: Submodule): PrimeIdeal[] {
  const pb = powerBasisOf(ZK);
  const T = pb.T;
  const Tbar = Poly.from(T.asExpr(), T.gens, { modulus: p });
  const [, fl] = Tbar.factorList();
  if (fl.length === 1 && first(fl)[1] === 1) return [new PrimeIdeal(ZK, p, pb.zero(), ZK.n, 1)];
  return fl.map(([t, e]) => new PrimeIdeal(ZK, p, pb.elementFromPoly(Poly.from(t.asExpr(), t.gens, { domain: 'ZZ' })), t.degree(), e));
}

/**
 * For an ideal I of ZK containing pZK, the kernel N of x -> x**p - x on G =
 * ZK/I over GF(p) (as a submodule of a complement G of I), and G. (SymPy
 * asserts that N starts with 1, which need not hold, see primeDecompSplitIdeal.)
 */
function primeDecompComputeKernel(I: Submodule, p: bigint, ZK: Submodule): [Submodule, Submodule] {
  const W = I.matrix;
  const [n, r] = W.shape;
  let B = r === 0 ? DomainMatrix.eye(n, ZZ) : W.hstack(DomainMatrix.eye(n, ZZ).extractSlice([0, n], [0, 1]));
  if (B.shape[1] < n) B = supplementASubspace(B.convertTo(GF(p))).convertTo(ZZ);
  let G = ZK.submoduleFromMatrix(B);
  // the multiplication table is computed before discarding the first r basis elements
  G.computeMultTab();
  G = G.discardBefore(r);
  const phi = new ModuleEndomorphism(G, (x) => x.pow(Number(p)).sub(x));
  return [phi.kernel(p), G];
}

/** The prime ideal for a maximal ideal I of ZK containing pZK. */
function primeDecompMaximalIdeal(I: Submodule, p: bigint, ZK: Submodule): PrimeIdeal {
  const [m, n] = I.matrix.shape;
  const f = m - n;
  const G = dmMul(ZK.matrix, I.matrix);
  const pb = powerBasisOf(ZK);
  const gens = Array.from({ length: G.shape[1] }, (_, j) => pb.call(G.extractSlice([0, G.shape[0]], [j, j + 1]), ZK.denom));
  return new PrimeIdeal(ZK, p, twoEltRep(gens, ZK, p, f), f);
}

/** Split an ideal I of ZK containing pZK whose quotient is not a field, by an idempotent from a non-trivial factor of the minimal polynomial of an element. */
function primeDecompSplitIdeal(I: Submodule, p: bigint, N: Submodule, G: Submodule, ZK: Submodule): [Submodule, Submodule] {
  // an element of the kernel outside GF(p): SymPy asserts that N starts with 1 and takes N(1), but the
  // basis vector of 1 may be a multiple of it (prime_decomp(7, Poly(x**2 - 588)) fails); the first basis
  // vector of N that is not a multiple of G's first basis element 1 is taken, which is N(1) when N(0) is 1
  const j = N.matrix
    .transpose()
    .toList()
    .findIndex((c) => c.slice(1).some((v) => !v.equals(0)));
  const alpha = N.call(j).toParent();
  const alphaPowers: ModuleElement[] = [];
  const F = GF(p);
  const m = findMinPoly(alpha, F, undefined, alphaPowers);
  const [, fl] = m.factorList();
  const m1 = first(fl)[0];
  const m2 = m.quo(m1);
  const [U] = m1.gcdex(m2);
  const E = Poly.from(U.mul(m1).asExpr(), m.gens, { domain: 'ZZ' }).allCoeffs().map(int).reverse();
  let eps1: ModuleElement = G.zero();
  E.forEach((Ei, i) => (eps1 = eps1.add(at(alphaPowers, i).mul(Ei))));
  const eps2 = eps1.neg().add(1);
  const factor = (eps: ModuleElement): Submodule => {
    const e = eps.toParent();
    const D = I.matrix.convertTo(F).hstack(...ZK.basisElements().map((om) => e.mul(om).column(F)));
    const W = D.columnspace().convertTo(ZZ);
    return ZK.submoduleFromMatrix(W);
  };
  return [factor(eps1), factor(eps2)];
}

/** Options of primeDecomp. */
export interface PrimeDecompOptions {
  /** The polynomial of the field (needed unless ZK is given). */
  T?: Poly;
  /** The maximal order (computed by roundTwo unless given with dK). */
  ZK?: Submodule;
  /** The discriminant of the field. */
  dK?: Rational | bigint | number;
  /** The nilradical of ZK modulo p, if already known. */
  radical?: Submodule;
}

/**
 * The prime ideals of the maximal order lying above the rational prime p
 * (SymPy prime_decomp; Cohen, Alg. 6.2.9).
 *
 * SymPy compares p with the index of ZZ[theta] in ZK through the
 * discriminant of the T given, which is not the polynomial of ZK when T is
 * not monic over ZZ (roundTwo scales its roots); the discriminant of the
 * power basis of ZK is used here.
 */
export function primeDecomp(pIn: IntLike, opts: PrimeDecompOptions = {}): PrimeIdeal[] {
  const p = asInt(pIn, 'p');
  let T: Poly;
  if (opts.ZK !== undefined) {
    checkFormalConditionsForMaximalOrder(opts.ZK);
    T = opts.T ?? powerBasisOf(opts.ZK).T;
  } else if (opts.T !== undefined) T = opts.T;
  else throw new RangeError('At least one of T or ZK must be provided.');
  const radicals = new Map<bigint, Submodule>();
  let ZK: Submodule, dK: bigint;
  if (opts.dK === undefined || opts.ZK === undefined) {
    let d: Rational;
    [ZK, d] = roundTwo(T, { radicals });
    dK = d.p;
  } else {
    ZK = opts.ZK;
    dK = typeof opts.dK === 'object' ? int(opts.dK) : BigInt(opts.dK);
  }
  const dT = int(powerBasisOf(ZK).T.discriminant());
  const fSquared = fdiv(dT, dK);
  if (pmod(fSquared, p) !== 0n) return primeDecompEasyCase(p, ZK);
  const radical = opts.radical ?? radicals.get(p) ?? nilradicalModP(ZK, p);
  const stack = [radical];
  const primes: PrimeIdeal[] = [];
  for (let I = stack.pop(); I !== undefined; I = stack.pop()) {
    const [N, G] = primeDecompComputeKernel(I, p, ZK);
    if (N.n === 1) primes.push(primeDecompMaximalIdeal(I, p, ZK));
    else stack.push(...primeDecompSplitIdeal(I, p, N, G, ZK));
  }
  return primes;
}

numberFieldHooks.primeDecomp = (p, ZK, dK, radical) => primeDecomp(p, { ZK, dK, ...(radical ? { radical } : {}) });
