/**
 * The public API report (api-report.md): every export of every entry point
 * with its kind and stability level (stable, experimental, deprecated),
 * taken from the JSDoc tags. Changes to the public API show up as a diff of
 * this file in review. Regenerate with `UPDATE_API_REPORT=1 pnpm test`.
 */

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { expect, it } from 'vitest';

const root = fileURLToPath(new URL('..', import.meta.url));
const src = join(root, 'src');
const ENTRIES = ['core', 'special', 'simplify', 'polys', 'calculus', 'solvers', 'sets', 'matrices', 'logic', 'ntheory', 'combinatorics', 'utilities', 'tensor', 'printing', 'discrete', 'algebras', 'strategies', 'unify', 'holonomic', 'geometry'];

type Row = { name: string; kind: string; level: string };

/** JSDoc block immediately preceding the declaration of `name` in a module. */
function docOf(file: string, name: string): string {
  const text = readFileSync(join(src, file), 'utf8');
  const re = new RegExp(`(/\\*\\*(?:(?!\\*/)[\\s\\S])*\\*/)\\s*\\nexport (?:declare )?(?:abstract )?(?:class|function|const|let|type|interface) ${name}\\b`);
  return re.exec(text)?.[1] ?? '';
}

function levelOf(doc: string): string {
  if (/@deprecated/.test(doc)) return 'deprecated';
  if (/@experimental/.test(doc)) return 'experimental';
  return 'stable';
}

function rows(entry: string, mod: Record<string, unknown>): Row[] {
  const text = readFileSync(join(src, `${entry}.ts`), 'utf8');
  const origin = new Map<string, [string, string]>(); // exported name -> [module file, original name]
  for (const m of text.matchAll(/export (type )?\{([^}]*)\} from '\.\/([^']+)'/g)) {
    for (const spec of m[2]!.split(',').map((s) => s.trim()).filter(Boolean)) {
      const [orig, as] = spec.split(/\s+as\s+/);
      origin.set((as ?? orig)!, [`${m[3]}.ts`, orig!]);
    }
  }
  const out: Row[] = [];
  const types = new Set<string>();
  for (const m of text.matchAll(/export type \{([^}]*)\}/g)) for (const s of m[1]!.split(',').map((t) => t.trim()).filter(Boolean)) types.add(s.split(/\s+as\s+/).pop()!);
  for (const m of text.matchAll(/^export type (\w+)\b/gm)) if (!(m[1]! in mod)) types.add(m[1]!);
  for (const name of Object.keys(mod).sort()) {
    const v = mod[name];
    const kind = typeof v === 'function' ? (/^class\b/.test(Function.prototype.toString.call(v)) || /^[A-Z]/.test(name) && 'prototype' in (v as object) && Object.getOwnPropertyNames((v as { prototype: object }).prototype).length > 1 ? 'class' : 'function') : typeof v === 'object' ? 'object' : typeof v;
    const o = origin.get(name);
    const doc = o ? docOf(o[0], o[1]) : docOf(`${entry}.ts`, name);
    out.push({ name, kind, level: levelOf(doc) });
  }
  for (const t of [...types].sort()) {
    const o = origin.get(t);
    out.push({ name: t, kind: 'type', level: levelOf(o ? docOf(o[0], o[1]) : docOf(`${entry}.ts`, t)) });
  }
  return out;
}

it('api-report.md is up to date', async () => {
  let md = '# API report of `@symjs/symjs`\n\nGenerated by `tests/api-report.test.ts` (`UPDATE_API_REPORT=1 pnpm test`). Do not edit. Levels follow docs/api-policy.md.\n';
  const total = { stable: 0, experimental: 0, deprecated: 0 } as Record<string, number>;
  const sections: string[] = [];
  for (const entry of ENTRIES) {
    const mod = (await import(`../src/${entry}.ts`)) as Record<string, unknown>;
    const rs = rows(entry, mod);
    for (const r of rs) total[r.level] = (total[r.level] ?? 0) + 1;
    sections.push(`\n## \`@symjs/symjs/${entry}\` (${rs.length})\n\n| Export | Kind | Level |\n|---|---|---|\n` + rs.map((r) => `| \`${r.name}\` | ${r.kind} | ${r.level} |`).join('\n') + '\n');
  }
  md += `\nTotal: ${total['stable']} stable, ${total['experimental']} experimental, ${total['deprecated']} deprecated. The root \`@symjs/symjs\` re-exports every entry point.\n` + sections.join('');
  const file = join(root, 'api-report.md');
  if (process.env['UPDATE_API_REPORT'] || !existsSync(file)) writeFileSync(file, md);
  expect(readFileSync(file, 'utf8')).toBe(md);
  expect(readdirSync(src).filter((f) => f.endsWith('.ts') && f !== 'index.ts').map((f) => f.slice(0, -3)).sort()).toEqual([...ENTRIES].sort());
});
