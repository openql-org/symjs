/**
 * docs/api-policy.md, "Results of the public computation API": no public
 * function or method returns undefined or null. Undecidable answers are
 * Truth ('unknown'), a missing form NoMatch, no closed form Unsolved, no
 * solution EmptySet.
 *
 * The check is done by the compiler itself: a file with one type-level
 * assertion per public export (functions, including up to four overloads,
 * and the methods of exported classes) is generated and type-checked with
 * the project's tsc, so no compiler API is needed.
 */

import { execFileSync } from 'node:child_process';
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { expect, it } from 'vitest';

const repo = fileURLToPath(new URL('../../..', import.meta.url));
const dir = join(repo, 'packages/symjs/tests/.api-results');

/** The modules checked, as [import path from the generated file, runtime module]. */
const MODULES: [string, () => Promise<Record<string, unknown>>][] = [
  ['../../src/index', () => import('../src/index')],
  ['../../../physics-quantum/src/index', () => import('../../physics-quantum/src/index')],
  ['../../../mathjs/src/index', () => import('../../mathjs/src/index')],
];

/**
 * Allowed: the hooks of ExtensionExpr, which extension authors implement and
 * where undefined means "no override", and ExprMap.get (the Map contract).
 */
const HOOKS = ['numericValue', 'diffSelf', 'adjointSelf', 'conjugateSelf', 'transposeSelf', 'bindings', 'doitSelf', 'rewriteSelf', 'expandSelf', 'subsSelf', 'integrateSelf', 'simplifySelf', 'evalfSelf', 'kindSelf', 'trigsimpSelf'];
const ALLOWED: Record<string, string[]> = { ExprMap: ['get'] };

const PRELUDE = `/* eslint-disable */
// Generated by tests/api-results.test.ts; deleted after the check.
type Fn = (...a: any[]) => any;
type Ret<F> = F extends { (...a: any[]): infer R1; (...a: any[]): infer R2; (...a: any[]): infer R3; (...a: any[]): infer R4 }
  ? R1 | R2 | R3 | R4
  : F extends (...a: any[]) => infer R ? R : never;
type IsUnknown<T> = unknown extends T ? true : false;
type Nullish<T> = [T] extends [never] ? false : IsUnknown<T> extends true ? false : null extends T ? true : [T] extends [void] ? false : undefined extends T ? true : false;
type BadMethods<P, Skip> = { [K in Exclude<keyof P, Skip>]: P[K] extends Fn ? (Nullish<Ret<P[K]>> extends true ? K : never) : never }[Exclude<keyof P, Skip>];
type Proto<C> = C extends { prototype: infer P } ? P : never;
type Hooks = ${HOOKS.map((h) => `'${h}'`).join(' | ')};
`;

it('public functions and methods never return undefined or null', async () => {
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  let src = PRELUDE;
  for (const [i, [path, load]] of MODULES.entries()) {
    src += `import * as M${i} from '${path}';\n`;
    const mod = await load();
    for (const [name, value] of Object.entries(mod)) {
      if (typeof value !== 'function') continue;
      const t = `typeof M${i}.${name}`;
      src += `export const f${i}_${name}: Nullish<Ret<${t}>> extends true ? 'returns undefined or null' : true = true;\n`;
      if (value.prototype && Object.getOwnPropertyNames(value.prototype).length > 1) {
        const skip = ['Hooks', ...(ALLOWED[name] ?? []).map((m) => `'${m}'`)].join(' | ');
        src += `export const m${i}_${name}: [BadMethods<Proto<${t}>, ${skip}>] extends [never] ? true : BadMethods<Proto<${t}>, ${skip}> = true;\n`;
      }
    }
  }
  writeFileSync(join(dir, 'check.ts'), src);
  writeFileSync(join(dir, 'tsconfig.json'), JSON.stringify({ extends: '../../../../tsconfig.json', compilerOptions: { noEmit: true, noUnusedLocals: false }, include: ['check.ts'] }));
  let out = '';
  try {
    execFileSync(join(repo, 'node_modules/.bin/tsc'), ['-p', join(dir, 'tsconfig.json')], { encoding: 'utf8', stdio: 'pipe' });
  } catch (e) {
    out = String((e as { stdout?: string }).stdout ?? e);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
  // the line of each error names the export: f<i>_<name> (function) or m<i>_<name> (methods, listed in the message)
  const lines = src.split('\n');
  const offenders = [...out.matchAll(/check\.ts\((\d+),\d+\): error TS\d+: ([^\n]*)/g)].map((m) => {
    const decl = /export const [fm]\d+_(\w+)/.exec(lines[Number(m[1]) - 1] ?? '');
    return `${decl ? decl[1] : `line ${m[1]}`}: ${m[2]}`;
  });
  expect(offenders).toEqual([]);
}, 180_000);
