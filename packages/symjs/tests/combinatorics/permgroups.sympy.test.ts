/** A Python tuple in the printed table. */
class Tup {
  constructor(readonly items: unknown[]) {}
}
const tup = (...a: unknown[]): Tup => new Tup(a);
/** Python's repr of the values in the table. */
function repr(v: unknown): string {
  if (v instanceof Tup) return v.items.length === 1 ? `(${repr(v.items[0])},)` : `(${v.items.map(repr).join(', ')})`;
  if (Array.isArray(v)) return `[${v.map(repr).join(', ')}]`;
  if (typeof v === 'boolean') return v ? 'True' : 'False';
  if (v === NoMatch) return 'None';
  if (typeof v === 'string') return `'${v.replace(/\n/g, '\\n')}'`;
  return String(v);
}
