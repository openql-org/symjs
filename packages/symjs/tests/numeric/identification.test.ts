describe('pslq and findpoly', () => {
  it('find integer relations like mpmath', () => {
    // mpmath.pslq at mp.dps = 15 and 30
    expect(pslq([f('3.25'), F.ONE], 53)).toEqual([-4n, 13n]);
    expect(pslq([M.mpPi(P), F.ONE], P)).toBeUndefined();
    expect(pslq([M.mpPi(P), F.ONE], P, F.fromNumber(1e-6))).toBeUndefined();
    expect(pslq([F.ONE, F.ONE], P)).toEqual([1n, -1n]);
    expect(pslq([F.ONE, f('1e-40')], P)).toBeUndefined();
    expect(pslq([F.ONE, F.fromInt(2n), F.fromInt(3n)], P)).toEqual([1n, 1n, -1n]);
    expect(findpoly(F.sqrt(F.fromInt(2n), P), 2, P)).toEqual([-1n, 0n, 2n]);
    expect(findpoly(F.ZERO, 1, P)).toEqual([1n, 0n]);
    expect(findpoly(M.mpPi(P), 2, P)).toBeUndefined();
  });
  it('rejects invalid input like mpmath (ValueError; AssertionError for a tolerance below the precision)', () => {
    expect(() => pslq([F.ONE], P)).toThrow(RangeError);
    expect(() => pslq([F.ONE, F.ONE], 40)).toThrow(RangeError);
    expect(() => pslq([F.ONE, F.ZERO], P)).toThrow(RangeError);
    expect(() => pslq([F.ONE, F.ONE], P, f('1e-100'))).toThrow(RangeError);
  });
});
