it('builds strong generating sets with Schreier-Sims', () => {
  // S4 from a 4-cycle and a transposition; S5 from a 5-cycle and a transposition; a group with a non-minimal base
  const order = (base: number[], gens: Af[]): number => getTransversals(base, gens).reduce((n, t) => n * t.size, 1);
  for (const [gens, n] of [
    [[[1, 2, 3, 0], [1, 0, 2, 3]], 24],
    [[[1, 2, 3, 4, 0], [1, 0, 2, 3, 4]], 120],
    [[[0, 2, 1, 3, 4], [1, 0, 2, 3, 4]], 6],
    [[[1, 0, 3, 2, 4, 5], [2, 3, 0, 1, 4, 5], [0, 1, 2, 3, 5, 4]], 8],
    [[[0, 1, 2]], 1],
    [[[1, 2, 3, 4, 5, 0], [1, 0, 2, 3, 4, 5]], 720],
    [[[1, 2, 0, 3, 4, 5], [0, 1, 2, 4, 5, 3], [3, 4, 5, 0, 1, 2]], 18],
    [[[1, 2, 3, 4, 5, 6, 7, 0], [7, 6, 5, 4, 3, 2, 1, 0]], 16],
    [[[0, 2, 3, 1, 4], [1, 2, 0, 3, 4], [0, 1, 3, 4, 2]], 60],
  ] as [Af[], number][]) {
    const [base, sgs] = schreierSimsIncremental(gens);
    expect(order(base, sgs)).toBe(n);
  }
  expect(schreierSimsIncremental([[0, 1, 2]])).toEqual([[], [[0, 1, 2]]]);
  const [base, sgs] = schreierSimsIncremental([[1, 2, 3, 4, 5, 0], [1, 0, 2, 3, 4, 5]], [3, 4]);
  expect([base.slice(0, 2), order(base, sgs)]).toEqual([[3, 4], 720]);
  expect(schreierSimsIncremental([[0, 2, 1, 3, 4], [1, 0, 2, 3, 4]])[0]).toEqual([1, 0]);
});

it('gives the BSGS of the symmetric groups and of direct products', () => {
  expect(getSymmetricGroupSgs(1)).toEqual([[], [[0, 1, 2]]]);
  expect(getSymmetricGroupSgs(3)).toEqual([[0, 1], [[1, 0, 2, 3, 4], [0, 2, 1, 3, 4]]]);
  expect(getSymmetricGroupSgs(2, true)).toEqual([[0], [[1, 0, 3, 2]]]);
  expect(bsgsDirectProduct([0], [[1, 0, 2, 3]], [0], [[1, 0, 3, 2]])).toEqual([[0, 2], [[1, 0, 2, 3, 4, 5], [0, 1, 3, 2, 5, 4]]]);
  expect(bsgsDirectProduct([], [[0, 1, 2]], [], [[0, 1, 2]])).toEqual([[], [[0, 1, 2, 3]]]);
  expect(riemannBsgs()[0]).toEqual([0, 2]);
  expect(dummySgs([1, 2], 0, 4)).toEqual([[0, 2, 1, 3, 4, 5]]);
  expect(dummySgs([2, 3, 4, 5], 1, 8)).toEqual([
    [0, 1, 3, 2, 4, 5, 6, 7, 9, 8],
    [0, 1, 2, 3, 5, 4, 6, 7, 9, 8],
    [0, 1, 4, 5, 2, 3, 6, 7, 8, 9],
  ]);
  expect(() => dummySgs([0, 1, 2, 3, 4], 0, 4)).toThrow('List too large');
  expect(compareLists([1, 2], [1, 2, 0])).toBeLessThan(0);
  expect(afInvert([2, 0, 1])).toEqual([1, 2, 0]);
  expect(canonicalFree([], [[0, 1, 2, 3]], [1, 0, 2, 3], 2)).toEqual([1, 0, 2, 3]);
  expect(doubleCosetCanRep([[0, 1]], [0], [], [[0, 1, 2, 3]], [], [1, 0, 2, 3])).toEqual([0, 1, 2, 3]);
});

it('rejects inconsistent arguments', () => {
  const [b, gs] = getSymmetricGroupSgs(1);
  expect(() => canonicalize([1, 0, 2, 3], [[0, 1]], [], [b, gs, 2, 0])).toThrow('same number');
  expect(() => canonicalize([1, 0, 2, 3, 4, 5], [[0, 2]], [0], [b, gs, 4, 0])).toThrow('dummies is not valid');
  expect(() => canonicalize([1, 0, 2, 3], [], [], [b, gs, 3, 0])).toThrow('g has size 4, generators have size 5');
});

it('uses the naive algorithm when Schreier-Sims gives no minimal base', () => {
  // the symmetric and antisymmetric groups of 3 slots generated by (1 2) and (0 1)
  const sym: Af[] = [
    [0, 2, 1, 3, 4],
    [1, 0, 2, 3, 4],
  ];
  const asym: Af[] = [
    [0, 2, 1, 4, 3],
    [1, 0, 2, 4, 3],
  ];
  expect(canonicalize([2, 1, 0, 3, 4], [], [], [[], sym, 1, 0])).toEqual([0, 1, 2, 3, 4]);
  expect(canonicalize([2, 1, 0, 3, 4], [], [], [[], asym, 1, 0])).toEqual([0, 1, 2, 4, 3]);
  expect(canonicalize([1, 0, 2, 3, 4], [[1, 2]], [0], [[], asym, 1, 0])).toBe(0);
  expect(canonicalize([1, 0, 2, 3, 4], [[1, 2]], [null], [[], sym, 1, 0])).toEqual([0, 1, 2, 3, 4]);
});
