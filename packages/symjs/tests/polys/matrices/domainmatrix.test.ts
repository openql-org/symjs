// Tests of src/polys/matrices/domainmatrix.ts. Expected values are those of SymPy 1.14.

import { describe, expect, it } from 'vitest';
import { Rational, S, Sym } from '../../../src/core';
import { Matrix } from '../../../src/matrices/matrix';
import { QQ, RR, ZZ } from '../../../src/polys/domains';
import { DM, DomainMatrix } from '../../../src/polys/matrices/domainmatrix';
import { DomainScalar } from '../../../src/polys/matrices/domainscalar';
import { DDM } from '../../../src/polys/matrices/ddm';
import { SDM } from '../../../src/polys/matrices/sdm';
import { EXRAW } from '../../../src/polys/domains/expressionrawdomain';
import { DMBadInputError, DMDomainError, DMFormatError, DMNonInvertibleMatrixError, DMNonSquareMatrixError, DMNotAField, DMShapeError } from '../../../src/polys/matrices/exceptions';
import { NotImplementedError } from '../../../src/core/errors';
import { add, mul, pow } from '../../../src/core/ops';

const q = (p: number, d = 1) => Rational.of(BigInt(p), BigInt(d));
const s = (v: unknown): string => (Array.isArray(v) ? `[${v.map(s).join(', ')}]` : String(v));
const x = new Sym('x');
const A = () => DM([[1, 2], [3, 4]], ZZ);

describe('DomainMatrix construction and conversion', () => {
  it('builds dense and sparse matrices', () => {
    expect(String(A())).toBe('DomainMatrix([[1, 2], [3, 4]], (2, 2), ZZ)');
    expect(String(new DomainMatrix(new Map([[0, new Map([[0, q(5)]])]]), [2, 2], ZZ))).toBe('DomainMatrix({0: {0: 5}}, (2, 2), ZZ)');
    expect(String(new DomainMatrix([[q(1)]], [1, 1], ZZ, { fmt: 'sparse' }))).toBe('DomainMatrix({0: {0: 1}}, (1, 1), ZZ)');
    expect(String(new DomainMatrix(new Map([[0, new Map([[0, q(1)]])]]), [1, 1], ZZ, { fmt: 'dense' }))).toBe('DomainMatrix([[1]], (1, 1), ZZ)');
    expect(String(DM([], ZZ))).toBe('DomainMatrix([], (0, 0), ZZ)');
    expect(String(DomainMatrix.fromRep(new DDM([[q(1)]], [1, 1], ZZ)))).toBe('DomainMatrix([[1]], (1, 1), ZZ)');
    expect(String(DomainMatrix.fromListSympy(1, 2, [[1, q(1, 2)]]))).toBe('DomainMatrix([[1, 1/2]], (1, 2), QQ)');
    expect(() => DomainMatrix.fromListSympy(2, 2, [[1, 2]])).toThrow(DMBadInputError);
    expect(String(DomainMatrix.fromDictSympy(2, 2, new Map([[1, new Map([[0, x]])]])))).toBe('DomainMatrix({1: {0: x}}, (2, 2), ZZ[x])');
    expect(() => DomainMatrix.fromDictSympy(1, 1, new Map([[3, new Map([[0, 1]])]]))).toThrow(DMBadInputError);
    expect(() => DomainMatrix.fromDictSympy(1, 1, new Map([[0, new Map([[3, 1]])]]))).toThrow(DMBadInputError);
    const M = Matrix.of([[1, 2], [3, 4]]);
    expect(String(DomainMatrix.fromMatrix(M))).toBe('DomainMatrix({0: {0: 1, 1: 2}, 1: {0: 3, 1: 4}}, (2, 2), ZZ)');
    expect(String(DomainMatrix.fromMatrix(M, { fmt: 'dense', field: true }))).toBe('DomainMatrix([[1, 2], [3, 4]], (2, 2), QQ)');
    expect(String(DomainMatrix.getDomain([1, q(1, 2)])[0])).toBe('QQ');
    expect(String(DomainMatrix.fromListFlat([q(1), q(2)], [1, 2], ZZ))).toBe('DomainMatrix([[1, 2]], (1, 2), ZZ)');
    expect(String(DomainMatrix.fromDod(new Map([[0, new Map([[1, q(2)]])]]), [1, 2], ZZ))).toBe('DomainMatrix({0: {1: 2}}, (1, 2), ZZ)');
    expect(String(DomainMatrix.fromDok(new Map([[[0, 1] as const, q(2)]]), [1, 2], ZZ))).toBe('DomainMatrix({0: {1: 2}}, (1, 2), ZZ)');
    expect(String(DomainMatrix.eye(2, QQ))).toBe('DomainMatrix({0: {0: 1}, 1: {1: 1}}, (2, 2), QQ)');
    expect(String(DomainMatrix.eye([1, 2], QQ))).toBe('DomainMatrix({0: {0: 1}}, (1, 2), QQ)');
    expect(String(DomainMatrix.diag([q(5), q(6)], ZZ))).toBe('DomainMatrix({0: {0: 5}, 1: {1: 6}}, (2, 2), ZZ)');
    expect(String(DomainMatrix.zeros([2, 3], QQ))).toBe('DomainMatrix({}, (2, 3), QQ)');
    expect(String(DomainMatrix.ones([2, 3], QQ))).toBe('DomainMatrix([[1, 1, 1], [1, 1, 1]], (2, 3), QQ)');
  });
  it('converts between domains and formats', () => {
    const a = A();
    expect(String(a.toField())).toBe('DomainMatrix([[1, 2], [3, 4]], (2, 2), QQ)');
    expect(String(a.convertTo(ZZ))).toBe(String(a));
    expect(String(a.toSympy())).toBe('DomainMatrix([[1, 2], [3, 4]], (2, 2), EXRAW)');
    expect(a.toSparse().toSparse().rep).toBeInstanceOf(SDM);
    expect(a.toDense()).toBe(a);
    expect(a.toSparse().toDense().rep).toBeInstanceOf(DDM);
    expect(String(a.toDdm())).toBe('[[1, 2], [3, 4]]');
    expect(String(a.toSdm())).toBe('{0: {0: 1, 1: 2}, 1: {0: 3, 1: 4}}');
    expect(String(a.toDfmOrDdm())).toBe('[[1, 2], [3, 4]]');
    expect(String(a.chooseDomain({ field: true }))).toBe('DomainMatrix([[1, 2], [3, 4]], (2, 2), QQ)');
    expect(String(a.toMatrix())).toBe('Matrix([[1, 2], [3, 4]])');
    expect(s(a.toList())).toBe('[[1, 2], [3, 4]]');
    expect(s(a.toListFlat())).toBe('[1, 2, 3, 4]');
    expect(s(a.flat())).toBe('[1, 2, 3, 4]');
    expect(String(a.toDod().get(1)?.get(0))).toBe('3');
    expect([...a.toDok().values()].length).toBe(4);
    expect(s(a.iterValues())).toBe('[1, 2, 3, 4]');
    expect(a.iterItems().length).toBe(4);
    expect(String(a.fromDodLike(new Map([[0, new Map([[0, q(7)]])]])))).toBe('DomainMatrix([[7, 0], [0, 0]], (2, 2), ZZ)');
    expect(String(a.toSparse().fromDodLike(new Map(), QQ))).toBe('DomainMatrix({}, (2, 2), QQ)');
    const [u1, u2] = a.unify(a.toField());
    expect([String(u1?.domain), String(u2?.domain)]).toEqual(['QQ', 'QQ']);
    expect(a.unify(a).length).toBe(2);
    expect(a.unifyFmt([a.toSparse()], 'sparse').map((m) => m.rep.fmt)).toEqual(['sparse', 'sparse']);
    expect(a.unifyFmt([a], 'sparse').map((m) => m.rep.fmt)).toEqual(['dense', 'dense']);
  });
  it('indexes and extracts', () => {
    const a = A();
    expect(String(a.getitem(1, 0))).toBe('3');
    expect(String(a.getitemSympy(0, 1))).toBe('2');
    expect(String(a.extract([1], [0, 1]))).toBe('DomainMatrix([[3, 4]], (1, 2), ZZ)');
    expect(String(a.extractSlice(0, [1, null]))).toBe('DomainMatrix([[2]], (1, 1), ZZ)');
    expect(String(a.extractSlice([null, null], -1))).toBe('DomainMatrix([[2], [4]], (2, 1), ZZ)');
    expect(() => a.extractSlice(2, 0)).toThrow(RangeError);
    a.setitem(0, 0, q(9));
    expect(String(a)).toBe('DomainMatrix([[9, 2], [3, 4]], (2, 2), ZZ)');
    expect(a.nnz()).toBe(4);
    expect(String(a.transpose())).toBe('DomainMatrix([[9, 3], [2, 4]], (2, 2), ZZ)');
    expect([a.isZeroMatrix, a.isUpper, a.isLower, a.isDiagonal, a.isSquare]).toEqual([false, false, false, false, true]);
    expect(s(a.diagonal())).toBe('[9, 4]');
  });
});

describe('DomainMatrix arithmetic', () => {
  it('adds, multiplies and stacks', () => {
    const a = A();
    const b = DM([[5, 6], [7, 8]], ZZ);
    expect(String(a.add(b))).toBe('DomainMatrix([[6, 8], [10, 12]], (2, 2), ZZ)');
    expect(String(a.toSparse().add(b.toSparse()))).toBe('DomainMatrix({0: {0: 6, 1: 8}, 1: {0: 10, 1: 12}}, (2, 2), ZZ)');
    expect(String(a.sub(b))).toBe('DomainMatrix([[-4, -4], [-4, -4]], (2, 2), ZZ)');
    expect(String(a.toSparse().sub(b.toSparse()))).toBe('DomainMatrix({0: {0: -4, 1: -4}, 1: {0: -4, 1: -4}}, (2, 2), ZZ)');
    expect(() => a.add(b.toField())).toThrow(DMDomainError);
    expect(() => a.add(DM([[1]], ZZ))).toThrow(DMShapeError);
    expect(() => a.add(b.toSparse())).toThrow(DMFormatError);
    expect(String(a.neg())).toBe('DomainMatrix([[-1, -2], [-3, -4]], (2, 2), ZZ)');
    expect(String(a.mul(q(2)))).toBe('DomainMatrix([[2, 4], [6, 8]], (2, 2), ZZ)');
    expect(String(a.rmul(q(2)))).toBe('DomainMatrix([[2, 4], [6, 8]], (2, 2), ZZ)');
    expect(String(a.matmul(b))).toBe('DomainMatrix([[19, 22], [43, 50]], (2, 2), ZZ)');
    expect(String(a.toSparse().matmul(b.toSparse()))).toBe('DomainMatrix({0: {0: 19, 1: 22}, 1: {0: 43, 1: 50}}, (2, 2), ZZ)');
    expect(String(a.scalarmul(q(0)))).toBe('DomainMatrix({}, (2, 2), ZZ)');
    expect(String(a.scalarmul(q(1)))).toBe(String(a));
    expect(String(a.rscalarmul(q(3)))).toBe('DomainMatrix([[3, 6], [9, 12]], (2, 2), ZZ)');
    expect(String(a.mulElementwise(a))).toBe('DomainMatrix([[1, 4], [9, 16]], (2, 2), ZZ)');
    expect(String(a.toSparse().mulElementwise(a.toSparse()))).toBe('DomainMatrix({0: {0: 1, 1: 4}, 1: {0: 9, 1: 16}}, (2, 2), ZZ)');
    expect(String(a.div(2))).toBe('DomainMatrix([[1/2, 1], [3/2, 2]], (2, 2), QQ)');
    expect(String(a.div(q(1)))).toBe('DomainMatrix([[1, 2], [3, 4]], (2, 2), QQ)');
    expect(String(a.div(q(1, 2)))).toBe('DomainMatrix([[2, 4], [6, 8]], (2, 2), QQ)');
    expect(String(a.div(new DomainScalar(q(2), ZZ)))).toBe('DomainMatrix([[1/2, 1], [3/2, 2]], (2, 2), QQ)');
    expect(() => a.div(0)).toThrow(RangeError);
    expect(String(a.pow(0))).toBe('DomainMatrix({0: {0: 1}, 1: {1: 1}}, (2, 2), ZZ)');
    expect(a.pow(1)).toBe(a);
    expect(String(a.pow(3))).toBe('DomainMatrix([[37, 54], [81, 118]], (2, 2), ZZ)');
    expect(() => a.pow(-1)).toThrow(NotImplementedError);
    expect(() => DM([[1, 2]], ZZ).pow(2)).toThrow(DMNonSquareMatrixError);
    expect(String(a.hstack(b))).toBe('DomainMatrix([[1, 2, 5, 6], [3, 4, 7, 8]], (2, 4), ZZ)');
    expect(String(a.toSparse().hstack(b))).toBe('DomainMatrix({0: {0: 1, 1: 2, 2: 5, 3: 6}, 1: {0: 3, 1: 4, 2: 7, 3: 8}}, (2, 4), ZZ)');
    expect(String(a.vstack(b))).toBe('DomainMatrix([[1, 2], [3, 4], [5, 6], [7, 8]], (4, 2), ZZ)');
    expect(String(a.toSparse().vstack(b.toSparse()))).toBe('DomainMatrix({0: {0: 1, 1: 2}, 1: {0: 3, 1: 4}, 2: {0: 5, 1: 6}, 3: {0: 7, 1: 8}}, (4, 2), ZZ)');
    expect(String(a.applyfunc((e) => mul(e, 2)))).toBe('DomainMatrix([[2, 4], [6, 8]], (2, 2), ZZ)');
    expect(a.equals(A())).toBe(true);
    expect(a.equals(a.toSparse())).toBe(false);
    expect(a.equals(1)).toBe(false);
    expect(a.unifyEq(a.toField())).toBe(true);
    expect(a.unifyEq(DM([[1]], ZZ))).toBe(false);
  });
});

describe('DomainMatrix linear algebra', () => {
  it('rref, nullspace, rank and spaces', () => {
    const a = A();
    expect(String(a.rref()[0])).toBe('DomainMatrix([[1, 0], [0, 1]], (2, 2), QQ)');
    const [r, d, p] = a.rrefDen();
    expect([String(r), String(d), p]).toEqual(['DomainMatrix([[-2, 0], [0, -2]], (2, 2), ZZ)', '-2', [0, 1]]);
    expect(a.rank()).toBe(2);
    const B = DM([[1, 2, 3], [2, 4, 6]], ZZ);
    expect(String(B.nullspace())).toBe('DomainMatrix([[-2, 1, 0], [-3, 0, 1]], (2, 3), ZZ)');
    expect(String(B.toField().nullspace({ divideLast: true }))).toBe('DomainMatrix([[-2, 1, 0], [-3, 0, 1]], (2, 3), QQ)');
    expect(() => B.nullspace({ divideLast: true })).toThrow(DMNotAField);
    expect(String(DM([[-2, -4]], ZZ).nullspace())).toBe('DomainMatrix([[-4, 2]], (1, 2), ZZ)');
    expect(String(DM([[1, -1], [2, -2]], QQ).columnspace())).toBe('DomainMatrix([[1], [2]], (2, 1), QQ)');
    expect(String(DM([[1, -1], [2, -2]], QQ).rowspace())).toBe('DomainMatrix([[1, -1]], (1, 2), QQ)');
    expect(() => a.columnspace()).toThrow(DMNotAField);
    expect(() => a.rowspace()).toThrow(DMNotAField);
    expect(String(DM([[0, 0]], QQ).nullspaceFromRref())).toBe('DomainMatrix([[1, 0], [0, 1]], (2, 2), QQ)');
  });
  it('determinant, inverse, adjugate and solving', () => {
    const a = A();
    expect(String(a.det())).toBe('-2');
    expect(() => DM([[1, 2]], ZZ).det()).toThrow(DMNonSquareMatrixError);
    expect(String(a.toField().inv())).toBe('DomainMatrix([[-2, 1], [3/2, -1/2]], (2, 2), QQ)');
    expect(() => a.inv()).toThrow(DMNotAField);
    expect(() => DM([[1, 2]], QQ).inv()).toThrow(DMNonSquareMatrixError);
    expect(String(a.adjugate())).toBe('DomainMatrix([[4, -2], [-3, 1]], (2, 2), ZZ)');
    expect(String(a.toSparse().adjDet()[0].toDense())).toBe('DomainMatrix([[4, -2], [-3, 1]], (2, 2), ZZ)');
    expect(a.invDen().map(String)).toEqual(['DomainMatrix([[4, -2], [-3, 1]], (2, 2), ZZ)', '-2']);
    const b = DM([[1], [2]], ZZ);
    expect(a.solveDen(b).map(String)).toEqual(['DomainMatrix([[0], [-1]], (2, 1), ZZ)', '-2']);
    expect(a.solveDen(b, 'charpoly').map(String)).toEqual(['DomainMatrix([[0], [-1]], (2, 1), ZZ)', '-2']);
    expect(() => a.solveDen(DM([[1]], ZZ))).toThrow(DMShapeError);
    expect(() => DM([[1, 2]], ZZ).solveDen(DM([[1]], ZZ), 'charpoly')).toThrow(DMNonSquareMatrixError);
    expect(() => a.solveDenRref(DM([[1]], ZZ))).toThrow(DMShapeError);
    expect(() => DM([[1, 2]], ZZ).solveDenRref(DM([[1]], ZZ))).toThrow(DMShapeError);
    expect(() => DM([[1, 2], [2, 4]], ZZ).solveDenRref(b)).toThrow(DMNonInvertibleMatrixError);
    expect(() => DM([[1, 2], [2, 4]], ZZ).solveDenCharpoly(b)).toThrow(DMNonInvertibleMatrixError);
    expect(() => DM([[1, 2]], ZZ).solveDenCharpoly(b)).toThrow(DMNonSquareMatrixError);
    expect(() => a.solveDenCharpoly(DM([[1]], ZZ))).toThrow(DMShapeError);
    expect(() => DM([[1, 2]], ZZ).adjPolyDet()).toThrow(DMNonSquareMatrixError);
    expect(s(DM([[2]], ZZ).adjPolyDet())).toBe('[[1], 2]');
    expect(String(a.evalPoly([q(1), q(2), q(3)]))).toBe('DomainMatrix([[12, 14], [21, 33]], (2, 2), ZZ)');
    expect(String(a.evalPoly([]))).toBe('DomainMatrix({}, (2, 2), ZZ)');
    expect(String(a.evalPoly([q(2)]))).toBe('DomainMatrix({0: {0: 2}, 1: {1: 2}}, (2, 2), ZZ)');
    expect(() => DM([[1, 2]], ZZ).evalPoly([])).toThrow(DMNonSquareMatrixError);
    expect(String(a.evalPolyMul([], b))).toBe('DomainMatrix({}, (2, 1), ZZ)');
    expect(() => DM([[1, 2]], ZZ).evalPolyMul([], b)).toThrow(DMNonSquareMatrixError);
    expect(() => a.evalPolyMul([], DM([[1]], ZZ))).toThrow(DMShapeError);
    expect(() => a.evalPolyMul([], b.toField())).toThrow(DMDomainError);
  });
  it('decompositions', () => {
    const a = A().toField();
    expect(a.lu().map(String)).toEqual(['DomainMatrix([[1, 0], [3, 1]], (2, 2), QQ)', 'DomainMatrix([[1, 2], [0, -2]], (2, 2), QQ)', '']);
    expect(() => A().lu()).toThrow(DMNotAField);
    expect(a.qr().map(String)).toEqual(['DomainMatrix([[1, 3/5], [3, -1/5]], (2, 2), QQ)', 'DomainMatrix([[1, 7/5], [0, 1]], (2, 2), QQ)']);
    expect(A().fflu().map(String)).toEqual(['DomainMatrix([[1, 0], [0, 1]], (2, 2), ZZ)', 'DomainMatrix([[1, 0], [3, -2]], (2, 2), ZZ)', 'DomainMatrix([[1, 0], [0, -2]], (2, 2), ZZ)', 'DomainMatrix([[1, 2], [0, -2]], (2, 2), ZZ)']);
    expect(String(DM([[1, 2], [3, 4], [5, 6]], QQ).luSolve(DM([[1], [2], [3]], QQ)))).toBe('DomainMatrix([[0], [1/2]], (2, 1), QQ)');
    expect(String(DM([[1, 2], [3, 4]], QQ).toSparse().luSolve(DM([[1], [2]], QQ)))).toBe('DomainMatrix({0: {0: 0}, 1: {0: 1/2}}, (2, 1), QQ)'.replace('0: {0: 0}, ', ''));
    expect(() => a.luSolve(DM([[1]], QQ))).toThrow(DMShapeError);
    expect(() => A().luSolve(DM([[1], [2]], ZZ))).toThrow(DMNotAField);
  });
  it('characteristic polynomials', () => {
    const a = A();
    expect(s(a.charpoly())).toBe('[1, -5, -2]');
    expect(s(a.toField().charpolyBase())).toBe('[1, -5, -2]');
    expect(s(DM([[q(1, 2), q(1, 3)], [2, 4]], QQ).charpoly())).toBe('[1, -9/2, 4/3]');
    expect(s(DM([[q(1, 2), q(1, 3)], [2, 4]], QQ).charpolyFactorList())).toBe('[[[6, -27, 8], 1]]');
    expect(s(DM([[2, 0], [0, 2]], ZZ).charpolyFactorList())).toBe('[[[1, -2], 2]]');
    const M = DM([[6, -1, 0, 0], [9, 12, 0, 0], [0, 0, 1, 2], [0, 0, 5, 6]], ZZ);
    expect(s(M.charpolyFactorBlocks())).toBe('[[[1, -18, 81], 1], [[1, -7, -4], 1]]');
    expect(s(M.charpolyFactorList())).toBe('[[[1, -9], 2], [[1, -7, -4], 1]]');
    expect(s(DM([[1, 0], [0, 2]], ZZ).charpolyFactorList())).toBe('[[[1, -2], 1], [[1, -1], 1]]');
    expect(() => DM([[1, 2]], ZZ).charpolyFactorBlocks()).toThrow(DMNonSquareMatrixError);
    expect(() => DM([[1, 2]], ZZ).scc()).toThrow(DMNonSquareMatrixError);
    expect(s(DM([[x, 1], [1, x]], ZZ.polyRing(x)).charpoly())).toBe('[1, -2*x, x**2 - 1]');
    expect(() => DM([[x, 1], [1, x]], ZZ.polyRing(x)).charpolyFactorList()).toThrow(NotImplementedError);
  });
  it('denominators, content and primitive parts', () => {
    const a = A();
    expect(a.clearDenoms().map(String)).toEqual(['1', String(a)]);
    const F = DM([[q(1, 2), q(1, 3)], [0, q(1, 4)]], QQ);
    expect(F.clearDenoms().map(String)).toEqual(['12', 'DomainMatrix([[6, 4], [0, 3]], (2, 2), QQ)']);
    expect(F.clearDenomsRowwise().map(String)).toEqual(['DomainMatrix({0: {0: 6}, 1: {1: 4}}, (2, 2), ZZ)', 'DomainMatrix([[3, 2], [0, 1]], (2, 2), QQ)']);
    expect(F.clearDenomsRowwise(true)[1].domain).toBe(ZZ);
    expect(a.cancelDenomElementwise(q(2)).map(String)).toEqual(['DomainMatrix([[1, 1], [3, 2]], (2, 2), ZZ)', 'DomainMatrix([[2, 1], [2, 1]], (2, 2), ZZ)']);
    expect(a.cancelDenomElementwise(q(1))[1].toString()).toBe('DomainMatrix([[1, 1], [1, 1]], (2, 2), ZZ)');
    expect(() => a.cancelDenomElementwise(q(0))).toThrow(RangeError);
    expect(a.cancelDenom(q(-2)).map(String)).toEqual(['DomainMatrix([[-1, -2], [-3, -4]], (2, 2), ZZ)', '2']);
    expect(a.cancelDenom(q(3)).map(String)).toEqual([String(a), '3']);
    expect(a.cancelDenom(q(1)).map(String)).toEqual([String(a), '1']);
    expect(DM([[2, 2, 0]], ZZ).cancelDenom(q(-4)).map(String)).toEqual(['DomainMatrix([[-1, -1, 0]], (1, 3), ZZ)', '2']);
    expect(DM([[4, 6]], ZZ).cancelDenom(q(12)).map(String)).toEqual(['DomainMatrix([[2, 3]], (1, 2), ZZ)', '6']);
    expect(() => a.cancelDenom(q(0))).toThrow(RangeError);
    expect(String(DM([[2, 4], [4, 12]], ZZ).content())).toBe('2');
    expect(DM([[3, 6]], ZZ).primitive().map(String)).toEqual(['3', 'DomainMatrix([[1, 2]], (1, 2), ZZ)']);
    expect(a.primitive().map(String)).toEqual(['1', String(a)]);
    expect(String(DM([[q(2, 3), q(4, 9)]], QQ).content())).toBe('2/9');
    expect(DomainMatrix.zeros([1, 1], ZZ).primitive().map(String)).toEqual(['0', 'DomainMatrix({}, (1, 1), ZZ)']);
  });
  it('works over polynomial rings, fraction fields and RR', () => {
    const K = ZZ.polyRing(x);
    const M = DM([[x, 1], [1, x]], K);
    expect(String(M.det())).toBe('x**2 - 1');
    expect(M.rrefDen().map(String)).toEqual(['DomainMatrix([[x**2 - 1, 0], [0, x**2 - 1]], (2, 2), ZZ[x])', 'x**2 - 1', '0,1']);
    expect(String(M.nullspace())).toBe('DomainMatrix([], (0, 2), ZZ[x])');
    expect(String(M.toField().inv())).toBe('DomainMatrix([[x/(x**2 - 1), -1/(x**2 - 1)], [-1/(x**2 - 1), x/(x**2 - 1)]], (2, 2), ZZ(x))');
    expect(String(M.toField().div(x))).toBe('DomainMatrix([[1, 1/x], [1/x, 1]], (2, 2), ZZ(x))');
    expect(String(M.toField().charpolyBase())).toBe('1,-2*x,x**2 - 1');
    expect(DM([[1.0, 2], [3, 4]], RR).rref()[1]).toEqual([0, 1]);
    expect(String(DM([[S.Half, x]], EXRAW))).toBe('DomainMatrix([[1/2, x]], (1, 2), EXRAW)');
    expect(String(DM([[add(x, 1)], [pow(x, 2)]], EXRAW).rref()[1])).toBe('0');
  });
  it('covers the remaining branches', () => {
    expect(DM([[2, 4]], ZZ).cancelDenom(q(3)).map(String)).toEqual(['DomainMatrix([[2, 4]], (1, 2), ZZ)', '3']);
    expect(s(DM([[0, 1], [0, 0]], ZZ).charpoly())).toBe('[1, 0, 0]');
    expect(DM([[q(1, 2), q(1, 3)]], QQ).primitive().map(String)).toEqual(['1/6', 'DomainMatrix([[3, 2]], (1, 2), QQ)']);
  });
});
